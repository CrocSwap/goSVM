// Package compiler implements an intentionally small, checked Go-to-C frontend.
//
// Check certifies the on-chain Go subset and returns a backend-neutral
// CheckedProgram; the C emitter in this package lowers that value without
// applying any language rules of its own.
package compiler

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/token"
	"go/types"
	"gosvm/internal/library"
	"strings"
)

const prelude = `// Generated by gosvm. Do not edit.
typedef unsigned char u8;
typedef unsigned int u32;
typedef unsigned long long u64;
typedef long long i64;
typedef _Bool boolean;
#ifdef GOSVM_SLICE_VIEWS
typedef struct { u8 *ptr; i64 len,cap; } slice;
#define GOSVM_SLICE(p,n) ((slice){(p),(n),(n)})
#else
typedef struct { u8 *ptr; i64 len; } slice;
#define GOSVM_SLICE(p,n) ((slice){(p),(n)})
#endif
#ifdef GOSVM_SBF_V3
// Solana static syscall hash for abort (Murmur3 of "abort").
static __attribute__((noreturn)) void gosvm_abort(void) {
    ((void (*)(void))0xb6fc1a11ULL)();
    __builtin_unreachable();
}
#define abort gosvm_abort
#else
extern void abort(void) __attribute__((noreturn));
#endif
static u8 *at(slice s, u64 i) { if (i >= (u64)s.len) abort(); return s.ptr+i; }
`

type generator struct {
	*frontend
	bytes.Buffer
	externals      map[string]library.Binding
	names          map[types.Object]string
	memory         bool
	memoryWords    bool // Explicit SDK-2 snapshots opt into aligned aggregate copies.
	entry          types.Object
	currentResults *types.Tuple
	continueLabels []string
	next           int
}

// Source is a Go file in a single on-chain package.
type Source struct {
	Name string
	Data []byte
}

// Compile accepts one source file with a legacy byte-slice or SDK Context entrypoint.
// Unsupported constructs return source-located errors, never a best-effort translation.
func Compile(filename string, source []byte) ([]byte, error) {
	return CompileSources([]Source{{filename, source}})
}

// CompileSources checks a whole package. File order never affects generated output.
func CompileSources(sources []Source) (out []byte, err error) {
	return CompileProgram(&Program{Entry: "program", Packages: []PackageSources{{"program", sources}}})
}

// CompileProgram checks the on-chain package graph with Check, then emits it
// as one C unit. Every language rejection comes from Check.
func CompileProgram(program *Program) ([]byte, error) {
	checked, err := Check(program)
	if err != nil {
		return nil, err
	}
	return emitC(checked)
}

// emitC lowers a checked program to C. It applies no language rules; a state
// Check rules out is reported as an internal error, never translated.
func emitC(program *CheckedProgram) (out []byte, err error) {
	defer recoverCompileError(&err)
	g := &generator{frontend: newFrontend(program.Fset, program.Info), names: map[types.Object]string{}, memoryWords: program.SDK == 2}
	g.entry = program.Process
	g.externals = libraryBindings(program.Libraries)
	files := program.Files
	var decls []ast.Decl
	for _, file := range files {
		decls = append(decls, file.Decls...)
	}
	hasPointers, hasViews := false, false
	for _, file := range files {
		ast.Inspect(file, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.SliceExpr:
				hasViews = true
			case *ast.CallExpr:
				if id, ok := n.Fun.(*ast.Ident); ok {
					if _, builtin := g.info.Uses[id].(*types.Builtin); builtin && id.Name == "cap" && len(n.Args) == 1 {
						if _, slice := g.info.Types[n.Args[0]].Type.(*types.Slice); slice {
							hasViews = true
						}
					}
				}
			case *ast.StarExpr:
				hasPointers = true
			case *ast.UnaryExpr:
				if n.Op == token.AND {
					hasPointers = true
				}
			}
			return true
		})
	}
	if hasViews {
		g.WriteString("#define GOSVM_SLICE_VIEWS 1\n")
	}
	g.WriteString(prelude)
	if usesUint16(files, g.info) {
		// Only programs that use uint16 get the typedef, so every other
		// program's emitted C is byte-identical to earlier compilers.
		g.WriteString(uint16Prelude)
	}
	if hasViews {
		g.WriteString(viewRuntime)
	}
	if hasPointers || hasViews {
		g.WriteString(pointerRuntime)
		g.ensureMemory()
	}
	if len(program.Libraries) > 0 {
		g.ensureMemory()
		g.WriteString(libraryMemory)
	}
	if usesBits(g.info, files) {
		g.WriteString(bitsRuntime)
	}
	if program.SDKPackage != nil {
		ownedLifecycle := false
		for _, object := range g.info.Uses {
			fn, ok := object.(*types.Func)
			if ok && fn.Pkg() != nil && fn.Pkg().Path() == "gosvm/solana" && (fn.Name() == "ResizeAccount" || fn.Name() == "CloseAccount") {
				ownedLifecycle = true
			}
		}
		if program.SDK == 2 || ownedLifecycle {
			g.WriteString("\n#define GOSVM_SDK2 1\n")
		}
		g.WriteString(solanaRuntime)
		if program.SDK != 1 {
			g.WriteString(cpiRuntime)
		}
	}
	// Define value structs and array wrappers before function prototypes.
	emitted := map[types.Type]bool{}
	var emitType func(ast.Node, types.Type)
	emitType = func(node ast.Node, t types.Type) {
		named, ok := t.(*types.Named)
		if !ok {
			g.unchecked(node)
		}
		if emitted[t] {
			return
		}
		emitted[t] = true
		if a, ok := t.Underlying().(*types.Array); ok {
			g.emitArray(node, a)
			return
		}
		st, ok := t.Underlying().(*types.Struct)
		if !ok {
			g.variable(node, t)
			return
		}
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			if a, ok := f.Type().Underlying().(*types.Array); ok {
				g.emitArray(node, a)
			} else if _, ok := f.Type().Underlying().(*types.Struct); ok {
				emitType(node, f.Type())
			} else {
				g.variable(node, f.Type())
			}
		}
		g.line("typedef struct {")
		// C11 has no empty structs; Go's zero-sized value has no observable layout here.
		if st.NumFields() == 0 {
			g.line("u8 unused;")
		}
		for i := 0; i < st.NumFields(); i++ {
			f := st.Field(i)
			g.line("%s %s;", g.variable(node, f.Type()), g.name(f))
		}
		g.line("} %s;", g.name(named.Obj()))
	}
	// Anonymous arrays in signatures, locals and literals need the same wrapper
	// as named arrays with identical underlying types. Visit in source order;
	// iterating types.Info maps would make output/cache hashes nondeterministic.
	for _, f := range files {
		ast.Inspect(f, func(n ast.Node) bool {
			if n, ok := n.(*ast.ArrayType); ok && n.Len != nil {
				if tv, ok := g.info.Types[n]; ok {
					if a, ok := tv.Type.Underlying().(*types.Array); ok {
						g.emitArray(n, a)
					}
				}
			}
			return true
		})
	}
	for _, d := range decls {
		if gen, ok := d.(*ast.GenDecl); ok && gen.Tok == token.TYPE {
			for _, sp := range gen.Specs {
				ts := sp.(*ast.TypeSpec)
				emitType(ts, g.info.Defs[ts.Name].Type())
			}
		}
	}
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			g.emitResults(fn, g.info.Defs[fn.Name].Type().(*types.Signature).Results())
		}
	}
	for _, call := range bitsResults(g.info, files) {
		g.emitResults(call, g.info.Types[call].Type.(*types.Tuple))
	}
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			g.WriteString(g.signature(fn) + ";\n")
		}
	}
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			g.WriteString(g.signature(fn))
			g.currentResults = g.info.Defs[fn.Name].Type().(*types.Signature).Results()
			if b, ok := externalBinding(g.externals, g.info.Defs[fn.Name]); ok {
				g.emitLibraryBody(fn, b)
			} else if !g.emitPackedStore(fn) {
				g.block(fn.Body)
			}
		}
	}
	if program.EntryKind == EntryContext {
		g.WriteString("\n#define GOSVM_CONTEXT_ENTRY 1\n")
		g.WriteString(accountsABI)
	}
	return g.Bytes(), nil
}

// unchecked marks an emitter state that Check rules out. Reaching one is a
// compiler bug, reported as such rather than as a language error.
func (g *generator) unchecked(n ast.Node) {
	panic(compileError(fmt.Sprintf("%s: internal error: construct was not certified by Check", g.fset.Position(n.Pos()))))
}
func (g *generator) line(format string, args ...any) { fmt.Fprintf(&g.Buffer, format+"\n", args...) }
func (g *generator) name(o types.Object) string {
	if o == g.entry {
		return "go_Process"
	}
	if s := g.names[o]; s != "" {
		return s
	}
	g.next++
	s := fmt.Sprintf("v%d", g.next)
	g.names[o] = s
	return s
}

// ctype maps a type admitted by typeRule to its C representation.
func (g *generator) ctype(n ast.Node, t types.Type) string {
	if tuple, ok := t.(*types.Tuple); ok && tuple.Len() > 1 {
		return g.resultName(n, tuple)
	}
	if p, ok := pointer(t); ok {
		return g.pointerType(n, p)
	}
	if isContext(t) {
		return "Context *"
	}
	if s, ok := t.(*types.Slice); ok && types.Identical(s.Elem(), types.Typ[types.Uint8]) {
		return "slice"
	}
	if a, ok := t.Underlying().(*types.Array); ok {
		return g.arrayName(n, a)
	}
	if named, ok := t.(*types.Named); ok {
		if _, ok := named.Underlying().(*types.Struct); ok {
			return g.name(named.Obj())
		}
	}
	if b, ok := t.Underlying().(*types.Basic); ok {
		switch b.Kind() {
		case types.Uint8:
			return "u8"
		case types.Uint16:
			return "u16"
		case types.Uint32:
			return "u32"
		case types.Uint64, types.UntypedInt:
			return "u64"
		case types.Bool, types.UntypedBool:
			return "boolean"
		case types.Int:
			return "i64" // len/cap only; Check rejects signed storage and arithmetic.
		}
	}
	g.unchecked(n)
	return ""
}
func (g *generator) variable(n ast.Node, t types.Type) string { return g.ctype(n, t) }
func (g *generator) signature(fn *ast.FuncDecl) string {
	sig := g.info.Defs[fn.Name].Type().(*types.Signature)
	ret := "void"
	if sig.Results().Len() > 1 {
		ret = g.resultName(fn, sig.Results())
	}
	if sig.Results().Len() == 1 {
		ret = g.variable(fn, sig.Results().At(0).Type())
	}
	args := []string{}
	if recv := sig.Recv(); recv != nil {
		args = append(args, g.variable(fn, recv.Type())+" "+g.name(recv))
	}
	for i := 0; i < sig.Params().Len(); i++ {
		p := sig.Params().At(i)
		args = append(args, g.variable(fn, p.Type())+" "+g.name(p))
	}
	if len(args) == 0 {
		args = append(args, "void")
	}
	return "static " + ret + " " + g.name(g.info.Defs[fn.Name]) + "(" + strings.Join(args, ",") + ")"
}
func (g *generator) temp(n ast.Node, t types.Type, value string) string {
	g.next++
	name := fmt.Sprintf("t%d", g.next)
	g.line("%s %s = %s;", g.ctype(n, t), name, value)
	return name
}
func (g *generator) expr(e ast.Expr) string {
	tv := g.info.Types[e]
	if tv.IsNil() {
		if _, ok := tv.Type.(*types.Slice); ok {
			return "(slice){0}"
		}
		return "0"
	}
	if tv.Value != nil {
		if tv.Value.Kind() == constant.Bool {
			if constant.BoolVal(tv.Value) {
				return "1"
			}
			return "0"
		}
		v, ok := constant.Uint64Val(tv.Value)
		if !ok {
			g.unchecked(e)
		}
		return fmt.Sprintf("%dULL", v)
	}
	switch e := e.(type) {
	case *ast.ParenExpr:
		return g.expr(e.X)
	case *ast.Ident:
		o, ok := g.info.Uses[e].(*types.Var)
		if !ok {
			g.unchecked(e)
		}
		return g.temp(e, tv.Type, g.name(o))
	case *ast.SliceExpr:
		return g.sliceView(e)
	case *ast.StarExpr:
		return g.pointed(e.X)
	case *ast.CompositeLit:
		if a, ok := tv.Type.Underlying().(*types.Array); ok {
			return g.arrayLiteral(e, a)
		}
		st, ok := tv.Type.Underlying().(*types.Struct)
		if !ok {
			g.unchecked(e)
		}
		r := g.temp(e, tv.Type, "{0}")
		for i, elt := range e.Elts {
			field := i
			value := elt
			if kv, ok := elt.(*ast.KeyValueExpr); ok {
				value = kv.Value
				field = -1
				id := kv.Key.(*ast.Ident)
				for j := 0; j < st.NumFields(); j++ {
					if st.Field(j).Name() == id.Name {
						field = j
						break
					}
				}
			}
			v := g.expr(value)
			g.line("%s.%s = %s;", r, g.name(st.Field(field)), v)
		}
		return r
	case *ast.SelectorExpr:
		field, ok := g.info.Uses[e.Sel].(*types.Var)
		if !ok || !field.IsField() {
			g.unchecked(e)
		}
		x := g.expr(e.X)
		if p, ok := pointer(g.info.Types[e.X].Type); ok {
			return g.temp(e, tv.Type, g.checkedPointer(e, p, x)+"->"+g.name(field))
		}
		return g.temp(e, tv.Type, x+"."+g.name(field))
	case *ast.IndexExpr:
		if _, ok := pointer(g.info.Types[e.X].Type); ok {
			if a, ok := arrayValue(g.info.Types[e.X].Type); ok {
				base, index := g.arrayPointer(e.X), g.expr(e.Index)
				return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(%s,%s)", g.arrayName(e, a), base, index))
			}
		}
		if a, ok := g.info.Types[e.X].Type.Underlying().(*types.Array); ok {
			// Reading an element of addressable array storage does not copy the
			// entire array. This matters for the SBF stack at the size boundary.
			if g.info.Types[e.X].Addressable() {
				x, i := g.fieldTarget(e.X), g.expr(e.Index)
				return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(&(%s),%s)", g.arrayName(e, a), x, i))
			}
			x, i := g.expr(e.X), g.expr(e.Index)
			return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(&%s,%s)", g.arrayName(e, a), x, i))
		}
		x, i := g.expr(e.X), g.expr(e.Index)
		return g.temp(e, tv.Type, fmt.Sprintf("*at(%s,%s)", x, i))
	case *ast.BinaryExpr:
		sliceType := g.info.Types[e.X].Type
		if _, ok := sliceType.(*types.Slice); !ok {
			sliceType = g.info.Types[e.Y].Type
		}
		if _, ok := sliceType.(*types.Slice); ok {
			x, y := g.exprAs(e.X, sliceType), g.exprAs(e.Y, sliceType)
			return g.temp(e, tv.Type, fmt.Sprintf("((%s).ptr %s (%s).ptr)", x, e.Op, y))
		}
		if a, ok := g.info.Types[e.X].Type.Underlying().(*types.Array); ok {
			x, y := g.expr(e.X), g.expr(e.Y)
			comparison := fmt.Sprintf("%s_equal(%s,%s)", g.arrayName(e, a), x, y)
			if e.Op == token.NEQ {
				comparison = "!" + comparison
			} else if e.Op != token.EQL {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, comparison)
		}
		if _, ok := g.info.Types[e.X].Type.Underlying().(*types.Struct); ok {
			g.unchecked(e)
		}
		x := g.expr(e.X)
		if e.Op == token.LAND || e.Op == token.LOR {
			r := g.temp(e, tv.Type, x)
			cond := r
			if e.Op == token.LOR {
				cond = "!" + r
			}
			g.line("if (%s) {", cond)
			y := g.expr(e.Y)
			g.line("%s = %s;\n}", r, y)
			return r
		}
		y := g.expr(e.Y)
		if e.Op == token.SHL || e.Op == token.SHR {
			bits := 64
			switch g.ctype(e, tv.Type) {
			case "u8":
				bits = 8
			case "u16":
				bits = 16
			case "u32":
				bits = 32
			case "u64":
			default:
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, fmt.Sprintf("%s >= %d ? 0 : ((u64)%s %s %s)", y, bits, x, e.Op, y))
		}
		if e.Op == token.QUO || e.Op == token.REM {
			g.line("if (%s == 0) abort();", y)
		}
		op := e.Op.String()
		if e.Op == token.AND_NOT {
			op = "& ~"
		}
		// Widen first to avoid C's signed integer promotions for byte arithmetic.
		return g.temp(e, tv.Type, fmt.Sprintf("((u64)%s %s (u64)%s)", x, op, y))
	case *ast.UnaryExpr:
		if e.Op == token.AND {
			return g.temp(e, tv.Type, g.address(e.X))
		}
		x := g.expr(e.X)
		op := e.Op.String()
		switch e.Op {
		case token.NOT, token.ADD, token.SUB:
		case token.XOR:
			op = "~"
		default:
			g.unchecked(e)
		}
		return g.temp(e, tv.Type, fmt.Sprintf("(%s(u64)%s)", op, x))
	case *ast.CallExpr:
		if selector, ok := e.Fun.(*ast.SelectorExpr); ok {
			if selection := g.info.Selections[selector]; selection != nil && selection.Kind() != types.FieldVal {
				return g.methodCall(e, selector, selection)
			}
		}
		if g.info.Types[e.Fun].IsType() {
			if s, ok := tv.Type.(*types.Slice); ok && types.Identical(s.Elem(), types.Typ[types.Uint8]) {
				if len(e.Args) != 1 {
					g.unchecked(e)
				}
				if g.info.Types[e.Args[0]].IsNil() {
					return g.temp(e, tv.Type, "(slice){0}")
				}
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
			if _, ok := tv.Type.Underlying().(*types.Array); ok {
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
		}
		var o types.Object
		builtinName := ""
		switch callee := e.Fun.(type) {
		case *ast.SelectorExpr:
			id, ok := callee.X.(*ast.Ident)
			if !ok {
				g.unchecked(e)
			}
			imported, ok := g.info.Uses[id].(*types.PkgName)
			if !ok {
				g.unchecked(e)
			}
			if imported.Imported().Path() == "gosvm/solana" {
				return g.importedCall(e, callee)
			}
			if imported.Imported().Path() == bitsPath {
				return g.bitsCall(e)
			}
			o = g.info.Uses[callee.Sel]
		case *ast.Ident:
			o = g.info.Uses[callee]
			builtinName = callee.Name
		default:
			g.unchecked(e)
		}
		args := g.callValues(e)
		if _, ok := o.(*types.TypeName); ok {
			if len(args) != 1 {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, "("+g.variable(e, tv.Type)+")"+args[0])
		}
		if _, ok := o.(*types.Builtin); ok {
			if len(e.Args) == 1 {
				if a, ok := arrayValue(g.info.Types[e.Args[0]].Type); ok && (builtinName == "len" || builtinName == "cap") {
					return g.temp(e, tv.Type, fmt.Sprintf("%dULL", a.Len()))
				}
			}
			if builtinName != "len" && builtinName != "cap" {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, args[0]+"."+builtinName)
		}
		if _, ok := o.(*types.Func); !ok {
			g.unchecked(e)
		}
		call := g.name(o) + "(" + strings.Join(args, ",") + ")"
		if tup, ok := tv.Type.(*types.Tuple); ok && tup.Len() == 0 {
			g.line("%s;", call)
			return ""
		}
		return g.temp(e, tv.Type, call)
	default:
		g.unchecked(e)
	}
	return ""
}
func (g *generator) block(b *ast.BlockStmt) {
	g.line("{")
	for _, s := range b.List {
		g.stmt(s)
	}
	g.line("}")
}
func (g *generator) stmt(s ast.Stmt) {
	switch s := s.(type) {
	case *ast.BlockStmt:
		g.block(s)
	case *ast.ReturnStmt:
		if g.currentResults != nil && g.currentResults.Len() > 1 {
			g.multiReturn(s)
			return
		}
		if len(s.Results) == 0 {
			g.line("return;")
		} else {
			v := g.exprAs(s.Results[0], g.currentResults.At(0).Type())
			g.line("return %s;", v)
		}
	case *ast.ExprStmt:
		g.expr(s.X)
	case *ast.AssignStmt:
		if s.Tok != token.DEFINE && s.Tok != token.ASSIGN {
			g.unchecked(s)
		}
		if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
			g.assignMany(s, s.Lhs, s.Rhs, s.Tok)
			return
		}
		switch lhs := s.Lhs[0].(type) {
		case *ast.Ident:
			if lhs.Name == "_" {
				g.expr(s.Rhs[0])
				return
			}
			o := g.info.Uses[lhs]
			if s.Tok == token.DEFINE {
				o = g.info.Defs[lhs]
			}
			v := g.exprAs(s.Rhs[0], o.Type())
			if s.Tok == token.DEFINE {
				if _, ok := o.Type().Underlying().(*types.Array); ok {
					// Array expressions already own a by-value temporary. Make it
					// the new variable's storage instead of copying a second time.
					g.names[o] = v
					return
				}
				g.line("%s %s = %s;", g.variable(lhs, o.Type()), g.name(o), v)
			} else {
				g.line("%s = %s;", g.name(g.info.Uses[lhs]), v)
			}
		case *ast.StarExpr:
			target := g.fieldTarget(lhs)
			v := g.expr(s.Rhs[0])
			g.line("%s = %s;", target, v)
		case *ast.SelectorExpr:
			target := g.fieldTarget(lhs)
			v := g.expr(s.Rhs[0])
			g.line("%s = %s;", target, v)
		case *ast.IndexExpr:
			if _, ok := pointer(g.info.Types[lhs.X].Type); ok {
				target := g.captureTarget(lhs)
				v := g.expr(s.Rhs[0])
				g.line("%s = %s;", target, v)
				return
			}
			if a, ok := g.info.Types[lhs.X].Type.Underlying().(*types.Array); ok {
				// Keep actual array storage, not an expression's by-value copy.
				x, i := g.fieldTarget(lhs.X), g.expr(lhs.Index)
				v := g.expr(s.Rhs[0])
				g.line("*%s_at(&(%s),%s) = %s;", g.arrayName(lhs, a), x, i, v)
				return
			}
			x, i := g.expr(lhs.X), g.expr(lhs.Index)
			v := g.expr(s.Rhs[0])
			g.line("*at(%s,%s) = %s;", x, i, v)
		default:
			g.unchecked(s)
		}
	case *ast.DeclStmt:
		d := s.Decl.(*ast.GenDecl)
		if d.Tok == token.CONST {
			return
		}
		if d.Tok != token.VAR {
			g.unchecked(s)
		}
		for _, sp := range d.Specs {
			v := sp.(*ast.ValueSpec)
			if len(v.Names) != 1 || len(v.Values) > 1 {
				g.multiDeclaration(v)
				continue
			}
			o := g.info.Defs[v.Names[0]]
			rhs := "{0}"
			if len(v.Values) == 1 {
				rhs = g.exprAs(v.Values[0], o.Type())
				if _, ok := o.Type().Underlying().(*types.Array); ok {
					g.names[o] = rhs
					continue
				}
			}
			g.line("%s %s = %s;", g.variable(v, o.Type()), g.name(o), rhs)
		}
	case *ast.IfStmt:
		g.line("{")
		if s.Init != nil {
			g.stmt(s.Init)
		}
		c := g.expr(s.Cond)
		g.line("if (%s)", c)
		g.block(s.Body)
		if s.Else != nil {
			g.line("else")
			g.stmt(s.Else)
		}
		g.line("}")
	case *ast.ForStmt:
		g.loop(s)
	case *ast.RangeStmt:
		g.rangeLoop(s)
	case *ast.SwitchStmt:
		g.switchStatement(s)
	case *ast.IncDecStmt:
		id, ok := s.X.(*ast.Ident)
		if !ok {
			target := g.captureTarget(s.X)
			g.line("(%s)%s;", target, s.Tok)
			return
		}
		g.line("%s%s;", g.name(g.info.Uses[id]), s.Tok)
	case *ast.BranchStmt:
		if s.Label != nil {
			g.unchecked(s)
		}
		switch s.Tok {
		case token.BREAK:
			g.line("break;")
		case token.CONTINUE:
			if len(g.continueLabels) == 0 {
				g.unchecked(s)
			}
			g.line("goto %s;", g.continueLabels[len(g.continueLabels)-1])
		default:
			g.unchecked(s)
		}
	case *ast.EmptyStmt:
	default:
		g.unchecked(s)
	}
}

// Targets preserve storage identity. Pointer operands are saved now; the
// returned target performs its nil check at the later load/address/store.
func (g *generator) fieldTarget(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		return g.name(g.info.Uses[e])
	case *ast.ParenExpr:
		return g.fieldTarget(e.X)
	case *ast.StarExpr:
		return "(*" + g.checkedPointer(e, g.info.Types[e.X].Type, g.expr(e.X)) + ")"
	case *ast.SelectorExpr:
		f, ok := g.info.Uses[e.Sel].(*types.Var)
		if !ok || !f.IsField() {
			g.unchecked(e)
		}
		if p, ok := pointer(g.info.Types[e.X].Type); ok {
			return g.checkedPointer(e, p, g.expr(e.X)) + "->" + g.name(f)
		}
		return g.fieldTarget(e.X) + "." + g.name(f)
	default:
		g.unchecked(e)
	}
	return ""
}
