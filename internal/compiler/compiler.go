// Package compiler implements an intentionally small, checked Go-to-C frontend.
//
// Check certifies the on-chain Go subset and returns a backend-neutral
// CheckedProgram; the C emitter in this package lowers that value without
// applying any language rules of its own.
package compiler

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/token"
	"go/types"
	"gosvm/internal/library"
	"strings"
)

const prelude = `// Generated by gosvm. Do not edit.
typedef unsigned char u8;
typedef unsigned int u32;
typedef unsigned long long u64;
typedef long long i64;
typedef _Bool boolean;
#ifdef GOSVM_SLICE_VIEWS
typedef struct { u8 *ptr; i64 len,cap; } slice;
#define GOSVM_SLICE(p,n) ((slice){(p),(n),(n)})
#else
typedef struct { u8 *ptr; i64 len; } slice;
#define GOSVM_SLICE(p,n) ((slice){(p),(n)})
#endif
#ifdef GOSVM_SBF_V3
// Solana static syscall hash for abort (Murmur3 of "abort").
static __attribute__((noreturn)) void gosvm_abort(void) {
    ((void (*)(void))0xb6fc1a11ULL)();
    __builtin_unreachable();
}
#define abort gosvm_abort
#else
extern void abort(void) __attribute__((noreturn));
#endif
static u8 *at(slice s, u64 i) { if (i >= (u64)s.len) abort(); return s.ptr+i; }
`

type generator struct {
	*frontend
	bytes.Buffer
	externals      map[string]library.Binding
	names          map[types.Object]string
	memory         bool
	memoryWords    bool // Explicit SDK-2 snapshots opt into aligned aggregate copies.
	entry          types.Object
	currentResults *types.Tuple
	fn             *fnContext // named results and defer statements of the body being emitted
	continueLabels []string
	next           int
	moved          map[types.Object]bool      // heap-moved locals (Function.HeapVars)
	movedLits      map[*ast.CompositeLit]bool // heap-moved &T{...} (Function.HeapLiterals)
	forward        map[any]bool               // structs (by structID) forward-declared for pointer fields
	defined        map[any]bool               // structs (by structID) whose definition was emitted
	movedParams    map[*ast.FuncDecl][]types.Object
	maps           *mapProgram // map types (CheckedProgram.Maps); nil without maps
	initializes    bool        // the program has package initialization (globals.go)
	// emitted and emittedInstances are the named types whose C definitions
	// were emitted; identical instances can be distinct *types.Named
	// (spelled with byte and uint8), so instances are also keyed.
	emitted          map[types.Type]bool
	emittedInstances map[string]bool
	// copied and copiedParams are the aggregate parameters a function or
	// literal receives under another name and copies into a local at entry;
	// opaqueCopies marks the copied parameters whose copies go through an
	// opaque pointer (byval.go).
	copied       map[types.Object]bool
	copiedParams map[ast.Node][]types.Object
	opaqueCopies map[types.Object]bool
	// writeSummaries are Check's call summaries (what calls may write).
	writeSummaries *evalAnalysis
	// order holds hoisted operands (CheckedProgram.Hoisted) while their owner
	// is emitted.
	order *hoisting
	// evaluatedStmts are the leading statements of package variable
	// initializers evaluated at compile time (PackageInit.EvaluatedVars).
	evaluatedStmts map[*ast.FuncDecl]int
}

// Source is a Go file in a single on-chain package.
type Source struct {
	Name string
	Data []byte
}

// Compile accepts one source file with a legacy byte-slice or SDK Context entrypoint.
// Unsupported constructs return source-located errors, never a best-effort translation.
func Compile(filename string, source []byte) ([]byte, error) {
	return CompileSources([]Source{{filename, source}})
}

// CompileSources checks a whole package. File order never affects generated output.
func CompileSources(sources []Source) (out []byte, err error) {
	return CompileProgram(&Program{Entry: "program", Packages: []PackageSources{{Path: "program", Sources: sources}}})
}

// CompileProgram checks the on-chain package graph with Check, then emits it
// as one C unit. Every language rejection comes from Check.
func CompileProgram(program *Program) ([]byte, error) {
	checked, err := Check(program)
	if err != nil {
		return nil, err
	}
	return emitC(checked)
}

// emitC lowers a checked program to C. It applies no language rules; a state
// Check rules out is reported as an internal error, never translated.
func emitC(program *CheckedProgram) ([]byte, error) {
	out, _, err := emitCNamed(program)
	return out, err
}

// emitCNamed is emitC that also maps the C names of the program's
// functions to their Go names.
func emitCNamed(program *CheckedProgram) (out []byte, names map[string]string, err error) {
	defer recoverCompileError(&err)
	g := &generator{frontend: newFrontend(program.Fset, program.Info), names: map[types.Object]string{}, memoryWords: program.SDK == 2,
		moved: map[types.Object]bool{}, movedLits: map[*ast.CompositeLit]bool{}, forward: map[any]bool{}, defined: map[any]bool{},
		movedParams: map[*ast.FuncDecl][]types.Object{}, emitted: map[types.Type]bool{}, emittedInstances: map[string]bool{},
		copied: map[types.Object]bool{}, copiedParams: map[ast.Node][]types.Object{}, opaqueCopies: map[types.Object]bool{}}
	for _, fn := range program.Functions {
		sig := fn.Object.Type().(*types.Signature)
		for _, v := range fn.HeapVars {
			g.moved[v] = true
			if v == sig.Recv() || isParameter(sig, v) {
				g.movedParams[fn.Decl] = append(g.movedParams[fn.Decl], v)
			}
		}
		for _, lit := range fn.HeapLiterals {
			g.movedLits[lit] = true
		}
	}
	// Aggregate parameters are copied at entry where the SBF backend's
	// byval lowering could otherwise share them with the caller (byval.go).
	summaries := program.order.analysis
	g.writeSummaries = summaries
	for _, fn := range program.Functions {
		if fn.Library != nil || fn.Intrinsic != "" {
			continue
		}
		sig := fn.Object.Type().(*types.Signature)
		var params []*types.Var
		if sig.Recv() != nil {
			params = append(params, sig.Recv())
		}
		for i := 0; i < sig.Params().Len(); i++ {
			params = append(params, sig.Params().At(i))
		}
		g.noteCopiedParams(fn.Decl, fn.Decl.Body, params, func() []ast.Node { return summaries.writeSites(fn.Decl.Body, nil, true, false) })
	}
	if program.funcs != nil {
		for _, cl := range program.funcs.closures {
			captured := map[types.Object]bool{}
			for _, v := range cl.Captures {
				captured[v] = true
			}
			g.noteCopiedParams(cl.Lit, cl.Lit.Body, cl.Params, func() []ast.Node { return summaries.writeSites(cl.Lit.Body, captured, true, false) })
		}
	}
	g.entry = program.Process
	g.externals = libraryBindings(program.Libraries)
	g.instantiated = program.Instantiated
	if program.ifaces != nil {
		g.ifaces = program.ifaces
	}
	if program.funcs != nil {
		g.funcs = program.funcs
	}
	g.maps = program.maps
	g.globals = program.globals
	g.initializes = program.initializes()
	g.panics = program.Panics
	order := program.order
	if order == nil {
		order = &evalOrder{}
	}
	g.order = &hoisting{order: order, value: map[ast.Expr]string{}, boxed: map[ast.Expr]string{}, used: map[ast.Expr]bool{}}
	for _, inst := range program.Instances {
		g.names[inst.Object] = inst.Symbol
	}
	files := program.lowered
	var decls []ast.Decl
	for _, file := range files {
		decls = append(decls, file.Decls...)
	}
	hasPointers, hasViews := false, false
	for _, file := range files {
		ast.Inspect(file, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.SliceExpr:
				hasViews = true
			case *ast.CallExpr:
				if id, ok := n.Fun.(*ast.Ident); ok {
					if _, builtin := g.info.Uses[id].(*types.Builtin); builtin && id.Name == "cap" && len(n.Args) == 1 {
						if _, slice := g.info.Types[n.Args[0]].Type.(*types.Slice); slice {
							hasViews = true
						}
					}
				}
			case *ast.StarExpr:
				hasPointers = true
			case *ast.UnaryExpr:
				if n.Op == token.AND {
					hasPointers = true
				}
			}
			return true
		})
	}
	// Allocation needs slice capacities and the pointer/memory helpers. Only
	// programs that use it get the heap runtime, so the C of every other
	// program is byte-identical to earlier compilers.
	// Interface values box into the heap and need its runtime too.
	// So do string concatenations and conversions (docs/GO_STRINGS.md).
	// Function values and defer records live there as well, and so do maps
	// (docs/GO_MAPS.md).
	hasHeap := usesAllocation(program) || g.ifaces.used || g.funcs.used || program.usesStrings && stringAllocates(g.info, files) || g.maps != nil || program.GlobalBytes > 0
	if hasHeap {
		hasViews, hasPointers = true, true
	}
	if hasViews {
		g.WriteString("#define GOSVM_SLICE_VIEWS 1\n")
	}
	g.WriteString(prelude)
	if usesUint16(files, g.info) {
		// Only programs that use uint16 get the typedef, so every other
		// program's emitted C is byte-identical to earlier compilers.
		g.WriteString(uint16Prelude)
	}
	if usesNarrowSigned(files, g.info) {
		g.WriteString(signedPrelude)
	}
	if usesSignedDivision(files, g.info) {
		g.WriteString(signedDivision)
	}
	if hasViews {
		g.WriteString(viewRuntime)
	}
	if hasPointers || hasViews {
		g.WriteString(pointerRuntime)
		g.ensureMemory()
	}
	if hasHeap {
		g.WriteString(heapRuntimeFor(program.Program.HeapBytes))
	}
	if program.usesStrings {
		// Only programs with string values get the string runtime, so the C
		// of every other program is byte-identical to earlier compilers.
		g.WriteString(stringRuntime)
		if hasHeap {
			g.WriteString(stringHeapRuntime)
		}
	}
	if g.ifaces.used {
		g.WriteString(ifaceRuntime)
	}
	if g.funcs.used {
		g.WriteString(funcRuntime)
	}
	if g.maps != nil {
		// Only programs with map values get the map runtime, so the C of
		// every other program is byte-identical to earlier compilers.
		g.WriteString(mapRuntime)
		if program.usesStrings {
			g.WriteString(stringHashRuntime)
		}
	}
	if program.usesEmpty {
		g.WriteString(emptyStructRuntime)
	}
	if len(program.Libraries) > 0 {
		g.ensureMemory()
		g.WriteString(libraryMemory)
	}
	if len(program.Panics) > 0 {
		// Only programs that call panic get its runtime, so the C of every
		// other program is byte-identical to earlier compilers.
		g.ensureMemory()
		g.WriteString(panicRuntime)
	}
	if usesBits(g.info, files) {
		g.WriteString(bitsRuntime)
		if usesUint16(files, g.info) {
			g.WriteString(bits16Runtime)
		}
	}
	if program.SDKPackage != nil {
		ownedLifecycle := false
		for _, object := range g.info.Uses {
			fn, ok := object.(*types.Func)
			if ok && fn.Pkg() != nil && fn.Pkg().Path() == "gosvm/solana" && (fn.Name() == "ResizeAccount" || fn.Name() == "CloseAccount") {
				ownedLifecycle = true
			}
		}
		if program.SDK == 2 || ownedLifecycle {
			g.WriteString("\n#define GOSVM_SDK2 1\n")
		}
		g.WriteString(solanaRuntime)
		if program.SDK != 1 {
			g.WriteString(cpiRuntime)
			if usesSDK(g.info, "GetReturnData") {
				g.WriteString(getReturnDataRuntime)
			}
			if usesSDK(g.info, "Secp256k1Recover") {
				g.WriteString(secp256k1RecoverRuntime)
			}
		}
	}
	// Define value structs and array wrappers before function prototypes.
	// Anonymous arrays in signatures, locals and literals need the same wrapper
	// as named arrays with identical underlying types. Visit in source order;
	// iterating types.Info maps would make output/cache hashes nondeterministic.
	for _, f := range files {
		ast.Inspect(f, func(n ast.Node) bool {
			if n, ok := n.(*ast.ArrayType); ok && n.Len != nil {
				if tv, ok := g.info.Types[n]; ok {
					if a, ok := tv.Type.Underlying().(*types.Array); ok {
						g.emitArray(n, a)
					}
				}
			}
			return true
		})
	}
	for _, a := range slotArrays(g.ifaces.slots) {
		g.emitArray(posNode(a.site), a.typ)
	}
	for _, d := range decls {
		if gen, ok := d.(*ast.GenDecl); ok && gen.Tok == token.TYPE {
			for _, sp := range gen.Specs {
				ts := sp.(*ast.TypeSpec)
				if ts.Assign.IsValid() {
					// An alias declares no type: its target is emitted at its
					// own declaration or instantiation, or needs no definition.
					continue
				}
				g.emitType(ts, g.info.Defs[ts.Name].Type())
			}
		}
	}
	for _, ti := range program.TypeInstances {
		g.emitType(posNode(ti.Site), ti.Type)
	}
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			g.emitResults(fn, g.info.Defs[fn.Name].Type().(*types.Signature).Results())
		}
	}
	for _, call := range bitsResults(g.info, files) {
		g.emitResults(call, g.info.Types[call].Type.(*types.Tuple))
	}
	for _, slot := range g.ifaces.slots {
		if slot.Called {
			g.emitResults(posNode(slot.Site), slot.Signature.Results())
		}
	}
	for _, cl := range g.funcs.closures {
		g.emitResults(cl.Lit, cl.Target.Signature.Results())
	}
	for _, class := range g.funcs.classes {
		g.emitResults(posNode(class.Site), class.Signature.Results())
	}
	// Package-level variables (docs/GO_GLOBALS.md); nothing without them.
	g.emitGlobals(program)
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			g.WriteString(g.signature(fn) + ";\n")
		}
	}
	for _, cl := range g.funcs.closures {
		g.WriteString(g.literalSignature(cl) + ";\n")
	}
	if g.ifaces.used {
		g.emitInterfaces(program)
	}
	if g.maps != nil {
		g.emitMaps()
	}
	g.emitFuncDispatchers()
	g.evaluatedStmts = map[*ast.FuncDecl]int{}
	for _, pi := range program.Inits {
		if pi.Vars != nil && pi.EvaluatedVars > 0 {
			g.evaluatedStmts[pi.Vars.Decl] = pi.EvaluatedVars
		}
	}
	functions := map[*ast.FuncDecl]*Function{}
	for _, function := range program.Functions {
		functions[function.Decl] = function
	}
	for _, d := range decls {
		if fn, ok := d.(*ast.FuncDecl); ok {
			sites := g.funcs.bodyDefers[fn]
			g.emitDeferTypes(fn, sites)
			g.WriteString(g.signature(fn))
			g.currentResults = g.info.Defs[fn.Name].Type().(*types.Signature).Results()
			named := namedResults(g.currentResults)
			if b, ok := externalBinding(g.externals, g.info.Defs[fn.Name]); ok {
				g.emitLibraryBody(fn, b)
			} else if function := functions[fn]; function != nil && function.Intrinsic != "" {
				g.emitIntrinsicBody(fn, function.Intrinsic)
			} else if len(sites) > 0 || named != nil {
				g.line("{")
				g.movedPrologue(fn)
				g.copyPrologue(fn)
				g.emitBody(fn, fn.Body, g.currentResults, named, sites)
				g.line("}")
			} else if len(g.movedParams[fn]) > 0 || len(g.copiedParams[fn]) > 0 {
				g.line("{")
				g.movedPrologue(fn)
				g.copyPrologue(fn)
				g.block(fn.Body)
				g.line("}")
			} else if k := g.evaluatedStmts[fn]; k > 0 {
				// The statements evaluated at compile time are in the
				// initialization image (initeval_emit.go).
				g.block(&ast.BlockStmt{List: fn.Body.List[k:]})
			} else if !g.emitPackedStore(fn) {
				g.block(fn.Body)
			}
			for _, cl := range g.funcs.owned[functions[fn]] {
				g.emitLiteral(cl)
			}
		}
	}
	g.emitInit(program)
	if program.EntryKind == EntryContext {
		g.WriteString("\n#define GOSVM_CONTEXT_ENTRY 1\n")
		g.WriteString(accountsABI)
	}
	names = map[string]string{}
	for o, name := range g.names {
		if fn, ok := o.(*types.Func); ok {
			names[name] = fn.FullName()
		}
	}
	if fn, ok := g.entry.(*types.Func); ok && fn != nil {
		names[g.rawName(fn)] = fn.FullName()
	}
	return g.Bytes(), names, nil
}

// compileProgramNamed is CompileProgram that also maps the C names of the
// program's functions to their Go names, for backend diagnostics.
func compileProgramNamed(program *Program) ([]byte, map[string]string, error) {
	checked, err := Check(program)
	if err != nil {
		return nil, nil, err
	}
	return emitCNamed(checked)
}

// unchecked marks an emitter state that Check rules out. Reaching one is a
// compiler bug, reported as such rather than as a language error.
func (g *generator) unchecked(n ast.Node) {
	panic(compileError(fmt.Sprintf("%s: internal error: construct was not certified by Check", g.fset.Position(n.Pos()))))
}
func (g *generator) line(format string, args ...any) { fmt.Fprintf(&g.Buffer, format+"\n", args...) }

// name is how C code refers to an object; a heap-moved variable is reached
// through its pointer.
func (g *generator) name(o types.Object) string {
	if g.moved[o] {
		return "(*" + g.rawName(o) + ")"
	}
	return g.rawName(o)
}

// rawName is the object's C identifier.
func (g *generator) rawName(o types.Object) string {
	if o == g.entry {
		if g.initializes {
			return entryBody // go_Process initializes first (globals.go)
		}
		return "go_Process"
	}
	if field, ok := o.(*types.Var); ok && field.IsField() {
		// Every instance of a generic struct names a field like the
		// declaration does (Origin is the field itself outside generics).
		o = field.Origin()
	}
	if s := g.names[o]; s != "" {
		return s
	}
	g.next++
	s := fmt.Sprintf("v%d", g.next)
	g.names[o] = s
	return s
}

// ctype maps a type admitted by typeRule to its C representation.
func (g *generator) ctype(n ast.Node, t types.Type) string {
	if tuple, ok := t.(*types.Tuple); ok && tuple.Len() > 1 {
		return g.resultName(n, tuple)
	}
	if p, ok := pointer(t); ok {
		return g.pointerType(n, p)
	}
	if isIface(t) {
		return "gosvm_iface"
	}
	if isFuncValue(t) {
		return "gosvm_func"
	}
	if isMap(t) {
		return "gosvm_map *" // every map type shares the header; see maps.go
	}
	if isEmptyStruct(t) {
		return "gosvm_empty"
	}
	if isContext(t) {
		return "Context *"
	}
	if _, ok := t.(*types.Slice); ok {
		return "slice" // every element type shares the descriptor; see element()
	}
	if a, ok := t.Underlying().(*types.Array); ok {
		return g.arrayName(n, a)
	}
	if named, ok := t.(*types.Named); ok {
		if _, ok := named.Underlying().(*types.Struct); ok {
			return g.structName(named)
		}
	}
	if b, ok := t.Underlying().(*types.Basic); ok {
		switch b.Kind() {
		case types.String, types.UntypedString:
			return "gosvm_string"
		case types.Uint8:
			return "u8"
		case types.Uint16:
			return "u16"
		case types.Uint32:
			return "u32"
		case types.Uint64, types.Uint, types.UntypedInt:
			return "u64"
		case types.Bool, types.UntypedBool:
			return "boolean"
		case types.Int8:
			return "i8"
		case types.Int16:
			return "i16"
		case types.Int32:
			return "i32"
		case types.Int64, types.Int:
			return "i64"
		}
	}
	g.unchecked(n)
	return ""
}
func (g *generator) variable(n ast.Node, t types.Type) string { return g.ctype(n, t) }

// structID identifies a struct for forward declarations without naming it:
// its object, or for an instantiated generic struct its key (identical
// instances can be distinct *types.Named, spelled with byte and uint8).
func structID(named *types.Named) any {
	if named.TypeArgs().Len() > 0 {
		return typeKey(named)
	}
	return named.Obj()
}

// structName is a value struct's C name; an instantiated generic struct is
// named by its key, so every instance has its own deterministic name.
func (g *generator) structName(named *types.Named) string {
	if named.TypeArgs().Len() > 0 {
		return "gosvm_ty_" + mangle(typeKey(named))
	}
	return g.name(named.Obj())
}
func (g *generator) signature(fn *ast.FuncDecl) string {
	sig := g.info.Defs[fn.Name].Type().(*types.Signature)
	ret := "void"
	if sig.Results().Len() > 1 {
		ret = g.resultName(fn, sig.Results())
	}
	if sig.Results().Len() == 1 {
		ret = g.variable(fn, sig.Results().At(0).Type())
	}
	args := []string{}
	parameter := func(o types.Object) string {
		if g.moved[o] {
			return g.movedParameter(o)
		}
		if g.copied[o] {
			return g.copiedParameter(o)
		}
		return g.name(o)
	}
	if recv := sig.Recv(); recv != nil {
		args = append(args, g.variable(fn, recv.Type())+" "+parameter(recv))
	}
	for i := 0; i < sig.Params().Len(); i++ {
		p := sig.Params().At(i)
		args = append(args, g.variable(fn, p.Type())+" "+parameter(p))
	}
	if len(args) == 0 {
		args = append(args, "void")
	}
	return "static " + ret + " " + g.name(g.info.Defs[fn.Name]) + "(" + strings.Join(args, ",") + ")"
}
func (g *generator) temp(n ast.Node, t types.Type, value string) string {
	g.next++
	name := fmt.Sprintf("t%d", g.next)
	g.line("%s %s = %s;", g.ctype(n, t), name, value)
	return name
}

// expr evaluates e; a value Check recorded as converted to an interface is
// converted.
func (g *generator) expr(e ast.Expr) string {
	if v, ok := g.hoisted(e, true); ok {
		return v
	}
	if conv := g.ifaces.byExpr[e]; conv != nil && !conv.rng {
		return g.convert(e, conv)
	}
	return g.exprValue(e)
}

func (g *generator) exprValue(e ast.Expr) string {
	if v, ok := g.hoisted(e, false); ok {
		return v
	}
	// Evaluation order (CheckedProgram.Hoisted): an owner's sequenced
	// operands first, when left to right would observably differ.
	defer g.hoist(e)()
	tv := g.info.Types[e]
	if tv.IsNil() {
		if _, ok := tv.Type.(*types.Slice); ok {
			return "(slice){0}"
		}
		return "0"
	}
	if tv.Value != nil {
		if tv.Value.Kind() == constant.String {
			return stringLiteral(tv.Value) // read-only data; nothing is allocated
		}
		if tv.Value.Kind() == constant.Bool {
			if constant.BoolVal(tv.Value) {
				return "1"
			}
			return "0"
		}
		if isSigned(tv.Type) {
			if negative, ok := signedConstant(tv.Value); ok {
				return negative
			}
		}
		v, ok := constant.Uint64Val(tv.Value)
		if !ok {
			g.unchecked(e)
		}
		return fmt.Sprintf("%dULL", v)
	}
	if t := g.funcs.byExpr[e]; t != nil {
		return g.funcValue(e, t)
	}
	switch e := e.(type) {
	case *ast.ParenExpr:
		return g.expr(e.X)
	case *ast.Ident:
		o, ok := g.info.Uses[e].(*types.Var)
		if !ok {
			g.unchecked(e)
		}
		return g.temp(e, tv.Type, g.name(o))
	case *ast.SliceExpr:
		if isString(g.info.Types[e.X].Type) {
			return g.stringSlice(e)
		}
		return g.sliceView(e)
	case *ast.StarExpr:
		return g.pointed(e.X)
	case *ast.CompositeLit:
		if a, ok := tv.Type.Underlying().(*types.Array); ok {
			return g.arrayLiteral(e, a)
		}
		if s, ok := tv.Type.(*types.Slice); ok {
			return g.sliceLiteral(e, s)
		}
		if isMap(tv.Type) {
			return g.mapLiteral(e, tv.Type)
		}
		literal := tv.Type
		if p, ok := pointer(literal); ok {
			literal = p.Elem() // an elided &T{...} element, boxed below
		}
		st, ok := literal.Underlying().(*types.Struct)
		if !ok {
			g.unchecked(e)
		}
		r := g.temp(e, literal, "{0}")
		for i, elt := range e.Elts {
			field := i
			value := elt
			if kv, ok := elt.(*ast.KeyValueExpr); ok {
				value = kv.Value
				field = -1
				id := kv.Key.(*ast.Ident)
				for j := 0; j < st.NumFields(); j++ {
					if st.Field(j).Name() == id.Name {
						field = j
						break
					}
				}
			}
			v := g.exprAs(value, st.Field(field).Type())
			g.line("%s.%s = %s;", r, g.name(st.Field(field)), v)
		}
		if literal != tv.Type {
			return g.box(e, literal, r)
		}
		return r
	case *ast.SelectorExpr:
		if v := g.packageVar(e); v != nil {
			return g.temp(e, tv.Type, g.name(v)) // pkg.V
		}
		field, ok := g.info.Uses[e.Sel].(*types.Var)
		if !ok || !field.IsField() {
			g.unchecked(e)
		}
		if arrayElement(g.info, e.X) {
			// A field of an array element is read in place.
			return g.temp(e, tv.Type, g.fieldTarget(e.X)+"."+g.name(field))
		}
		x := g.expr(e.X)
		if p, ok := pointer(g.info.Types[e.X].Type); ok {
			return g.temp(e, tv.Type, g.checkedPointer(e, p, x)+"->"+g.name(field))
		}
		return g.temp(e, tv.Type, x+"."+g.name(field))
	case *ast.IndexExpr:
		if isMap(g.info.Types[e.X].Type) {
			return g.mapIndex(e)
		}
		if _, ok := pointer(g.info.Types[e.X].Type); ok {
			if a, ok := arrayValue(g.info.Types[e.X].Type); ok {
				base, index := g.arrayPointer(e.X), g.expr(e.Index)
				return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(%s,%s)", g.arrayName(e, a), base, index))
			}
		}
		if a, ok := g.info.Types[e.X].Type.Underlying().(*types.Array); ok {
			// Reading an element of addressable array storage does not copy the
			// entire array. This matters for the SBF stack at the size boundary.
			if g.info.Types[e.X].Addressable() {
				x, i := g.fieldTarget(e.X), g.expr(e.Index)
				return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(&(%s),%s)", g.arrayName(e, a), x, i))
			}
			x, i := g.expr(e.X), g.expr(e.Index)
			return g.temp(e, tv.Type, fmt.Sprintf("*%s_at(&%s,%s)", g.arrayName(e, a), x, i))
		}
		x, i := g.expr(e.X), g.expr(e.Index)
		if isString(g.info.Types[e.X].Type) {
			return g.temp(e, tv.Type, fmt.Sprintf("gosvm_str_at(%s,(u64)%s)", x, i))
		}
		if !isByteSlice(g.info.Types[e.X].Type) {
			return g.temp(e, tv.Type, g.element(e, g.info.Types[e.X].Type, x, i))
		}
		return g.temp(e, tv.Type, fmt.Sprintf("*at(%s,%s)", x, i))
	case *ast.TypeAssertExpr:
		return g.typeAssert(e)
	case *ast.BinaryExpr:
		if isIface(g.info.Types[e.X].Type) || isIface(g.info.Types[e.Y].Type) {
			x := g.expr(e.X)
			y := g.expr(e.Y)
			comparison := g.ifaceEqual(e, e.X, x, e.Y, y)
			if e.Op == token.NEQ {
				comparison = "!" + comparison
			} else if e.Op != token.EQL {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, comparison)
		}
		if isMap(g.info.Types[e.X].Type) || isMap(g.info.Types[e.Y].Type) {
			// A map compares only with nil.
			x, y := g.expr(e.X), g.expr(e.Y)
			return g.temp(e, tv.Type, fmt.Sprintf("(%s %s %s)", x, e.Op, y))
		}
		sliceType := g.info.Types[e.X].Type
		if _, ok := sliceType.(*types.Slice); !ok {
			sliceType = g.info.Types[e.Y].Type
		}
		if _, ok := sliceType.(*types.Slice); ok {
			x, y := g.exprAs(e.X, sliceType), g.exprAs(e.Y, sliceType)
			return g.temp(e, tv.Type, fmt.Sprintf("((%s).ptr %s (%s).ptr)", x, e.Op, y))
		}
		if a, ok := g.info.Types[e.X].Type.Underlying().(*types.Array); ok {
			x, y := g.expr(e.X), g.expr(e.Y)
			comparison := fmt.Sprintf("%s_equal(%s,%s)", g.arrayName(e, a), x, y)
			if e.Op == token.NEQ {
				comparison = "!" + comparison
			} else if e.Op != token.EQL {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, comparison)
		}
		if _, ok := g.info.Types[e.X].Type.Underlying().(*types.Struct); ok {
			// Non-blank fields compare in order, stopping at the first
			// difference (docs/GO_TYPES.md#struct-equality).
			x, y := g.expr(e.X), g.expr(e.Y)
			comparison := g.structEqual(e, g.info.Types[e.X].Type, x, y)
			if e.Op == token.NEQ {
				comparison = "!" + comparison
			} else if e.Op != token.EQL {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, comparison)
		}
		if isString(g.info.Types[e.X].Type) {
			return g.stringBinary(e, tv)
		}
		x := g.expr(e.X)
		if e.Op == token.LAND || e.Op == token.LOR {
			r := g.temp(e, tv.Type, x)
			cond := r
			if e.Op == token.LOR {
				cond = "!" + r
			}
			g.line("if (%s) {", cond)
			y := g.expr(e.Y)
			g.line("%s = %s;\n}", r, y)
			return r
		}
		y := g.expr(e.Y)
		if e.Op == token.SHL || e.Op == token.SHR {
			b, ok := tv.Type.Underlying().(*types.Basic)
			if !ok || b.Info()&types.IsInteger == 0 {
				g.unchecked(e)
			}
			g.shiftCount(e, y)
			if signed, ok := g.signedBinary(e, x, y); ok {
				return g.temp(e, tv.Type, signed)
			}
			return g.temp(e, tv.Type, fmt.Sprintf("%s >= %d ? 0 : ((u64)%s %s %s)", y, intWidth(tv.Type), x, e.Op, y))
		}
		if signed, ok := g.signedBinary(e, x, y); ok {
			return g.temp(e, tv.Type, signed)
		}
		if e.Op == token.QUO || e.Op == token.REM {
			g.line("if (%s == 0) abort();", y)
		}
		op := e.Op.String()
		if e.Op == token.AND_NOT {
			op = "& ~"
		}
		// Widen first to avoid C's signed integer promotions for byte arithmetic.
		return g.temp(e, tv.Type, fmt.Sprintf("((u64)%s %s (u64)%s)", x, op, y))
	case *ast.UnaryExpr:
		if e.Op == token.AND {
			return g.temp(e, tv.Type, g.address(e.X))
		}
		x := g.expr(e.X)
		op := e.Op.String()
		switch e.Op {
		case token.NOT, token.ADD, token.SUB:
		case token.XOR:
			op = "~"
		default:
			g.unchecked(e)
		}
		return g.temp(e, tv.Type, fmt.Sprintf("(%s(u64)%s)", op, x))
	case *ast.CallExpr:
		if selector, ok := e.Fun.(*ast.SelectorExpr); ok {
			if selection := g.info.Selections[selector]; selection != nil && selection.Kind() != types.FieldVal {
				return g.methodCall(e, selector, selection)
			}
		}
		if g.info.Types[e.Fun].IsType() {
			if kind := classifyConversion(g.info, e); kind != notStringConversion {
				return g.stringConversion(e, kind)
			}
			if a, ptr, ok := sliceToArray(g.info, e); ok {
				return g.sliceToArray(e, tv.Type, a, ptr)
			}
			if isIface(tv.Type) {
				return g.expr(e.Args[0]) // converted, or copied from an interface value
			}
			if isMap(tv.Type) {
				if g.info.Types[e.Args[0]].IsNil() {
					return g.temp(e, tv.Type, "0")
				}
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
			if _, ok := tv.Type.(*types.Slice); ok {
				if len(e.Args) != 1 {
					g.unchecked(e)
				}
				if g.info.Types[e.Args[0]].IsNil() {
					return g.temp(e, tv.Type, "(slice){0}")
				}
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
			if _, ok := tv.Type.Underlying().(*types.Array); ok {
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
			if isFuncValue(tv.Type) {
				return g.temp(e, tv.Type, g.expr(e.Args[0]))
			}
			if _, ok := tv.Type.Underlying().(*types.Pointer); ok {
				// The same address as the converted type's C pointer.
				return g.temp(e, tv.Type, fmt.Sprintf("((%s)(%s))", g.variable(e, tv.Type), g.expr(e.Args[0])))
			}
		}
		var o types.Object
		builtinName := ""
		switch callee := g.callFun(e.Fun).(type) {
		case *ast.SelectorExpr:
			id, ok := callee.X.(*ast.Ident)
			if !ok {
				return g.indirectCall(e)
			}
			imported, ok := g.info.Uses[id].(*types.PkgName)
			if !ok {
				return g.indirectCall(e)
			}
			if imported.Imported().Path() == "gosvm/solana" {
				return g.importedCall(e, callee)
			}
			if imported.Imported().Path() == bitsPath {
				return g.bitsCall(e)
			}
			o = g.callee(callee.Sel)
			if _, ok := o.(*types.Var); ok {
				return g.indirectCall(e) // a function-valued package-level variable
			}
		case *ast.Ident:
			o = g.callee(callee)
			builtinName = callee.Name
			if _, ok := o.(*types.Var); ok {
				return g.indirectCall(e)
			}
		default:
			return g.indirectCall(e)
		}
		if b, ok := o.(*types.Builtin); ok && allocBuiltins[b.Name()] {
			return g.allocBuiltin(e, b.Name())
		}
		if name, ok := g.mapBuiltinCall(e); ok {
			return g.mapBuiltin(e, name)
		}
		if b, ok := o.(*types.Builtin); ok && b.Name() == "panic" {
			g.panicCall(e)
			return ""
		}
		args := g.callValues(e)
		if _, ok := o.(*types.TypeName); ok {
			if len(args) != 1 {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, "("+g.variable(e, tv.Type)+")"+args[0])
		}
		if _, ok := o.(*types.Builtin); ok {
			if len(e.Args) == 1 {
				if a, ok := arrayValue(g.info.Types[e.Args[0]].Type); ok && (builtinName == "len" || builtinName == "cap") {
					return g.temp(e, tv.Type, fmt.Sprintf("%dULL", a.Len()))
				}
			}
			if builtinName != "len" && builtinName != "cap" {
				g.unchecked(e)
			}
			return g.temp(e, tv.Type, args[0]+"."+builtinName)
		}
		if _, ok := o.(*types.Func); !ok {
			g.unchecked(e)
		}
		call := g.name(o) + "(" + strings.Join(args, ",") + ")"
		if tup, ok := tv.Type.(*types.Tuple); ok && tup.Len() == 0 {
			g.line("%s;", call)
			return ""
		}
		return g.temp(e, tv.Type, call)
	default:
		g.unchecked(e)
	}
	return ""
}
func (g *generator) block(b *ast.BlockStmt) {
	g.line("{")
	for _, s := range b.List {
		g.stmt(s)
	}
	g.line("}")
}
func (g *generator) stmt(s ast.Stmt) {
	defer g.hoist(s)()
	switch s := s.(type) {
	case *ast.BlockStmt:
		g.block(s)
	case *ast.ReturnStmt:
		if g.fn != nil {
			g.returnStmt(s)
			return
		}
		if g.currentResults != nil && g.currentResults.Len() > 1 {
			g.multiReturn(s)
			return
		}
		if len(s.Results) == 0 {
			g.line("return;")
		} else {
			v := g.exprAs(s.Results[0], g.currentResults.At(0).Type())
			g.line("return %s;", v)
		}
	case *ast.ExprStmt:
		g.expr(s.X)
	case *ast.AssignStmt:
		if s.Tok == token.ADD_ASSIGN && len(s.Lhs) == 1 && isString(g.info.Types[s.Lhs[0]].Type) {
			g.stringAddAssign(s)
			return
		}
		if _, ok := compoundOps[s.Tok]; ok && len(s.Lhs) == 1 && isInteger(g.info.Types[s.Lhs[0]].Type) {
			g.compoundAssign(s)
			return
		}
		if s.Tok != token.DEFINE && s.Tok != token.ASSIGN {
			g.unchecked(s)
		}
		if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
			g.assignMany(s, s.Lhs, s.Rhs, s.Tok)
			return
		}
		switch lhs := s.Lhs[0].(type) {
		case *ast.Ident:
			if lhs.Name == "_" {
				g.expr(s.Rhs[0])
				return
			}
			o := g.info.Uses[lhs]
			if s.Tok == token.DEFINE {
				o = g.info.Defs[lhs]
			}
			v := g.exprAs(s.Rhs[0], o.Type())
			if s.Tok == token.DEFINE {
				if g.moved[o] {
					g.declareMoved(lhs, o, v)
					return
				}
				if _, ok := o.Type().Underlying().(*types.Array); ok {
					// Array expressions already own a by-value temporary. Make it
					// the new variable's storage instead of copying a second time.
					g.names[o] = v
					return
				}
				g.line("%s %s = %s;", g.variable(lhs, o.Type()), g.name(o), v)
			} else {
				g.line("%s = %s;", g.name(g.info.Uses[lhs]), v)
			}
		case *ast.StarExpr:
			target := g.fieldTarget(lhs)
			v := g.exprAs(s.Rhs[0], g.info.Types[lhs].Type)
			g.line("%s = %s;", target, v)
		case *ast.SelectorExpr:
			target := g.fieldTarget(lhs)
			v := g.exprAs(s.Rhs[0], g.info.Types[lhs].Type)
			g.line("%s = %s;", target, v)
		case *ast.IndexExpr:
			if isMap(g.info.Types[lhs.X].Type) {
				// The map and key, then the value, then the insertion.
				target := g.mapTarget(lhs)
				v := g.exprAs(s.Rhs[0], g.info.Types[lhs].Type)
				g.line("%s = %s;", target, v)
				return
			}
			if _, ok := pointer(g.info.Types[lhs.X].Type); ok {
				target := g.captureTarget(lhs)
				v := g.expr(s.Rhs[0])
				g.line("%s = %s;", target, v)
				return
			}
			if a, ok := g.info.Types[lhs.X].Type.Underlying().(*types.Array); ok {
				// Keep actual array storage, not an expression's by-value copy.
				x, i := g.fieldTarget(lhs.X), g.expr(lhs.Index)
				v := g.expr(s.Rhs[0])
				g.line("*%s_at(&(%s),%s) = %s;", g.arrayName(lhs, a), x, i, v)
				return
			}
			x, i := g.expr(lhs.X), g.expr(lhs.Index)
			if !isByteSlice(g.info.Types[lhs.X].Type) {
				v := g.exprAs(s.Rhs[0], g.info.Types[lhs].Type)
				g.line("%s = %s;", g.element(lhs, g.info.Types[lhs.X].Type, x, i), v)
				return
			}
			v := g.expr(s.Rhs[0])
			g.line("*at(%s,%s) = %s;", x, i, v)
		default:
			g.unchecked(s)
		}
	case *ast.DeclStmt:
		d := s.Decl.(*ast.GenDecl)
		if d.Tok == token.CONST {
			return
		}
		if d.Tok != token.VAR {
			g.unchecked(s)
		}
		for _, sp := range d.Specs {
			v := sp.(*ast.ValueSpec)
			release := g.hoist(v)
			g.valueSpec(v)
			release()
		}
	case *ast.IfStmt:
		g.line("{")
		if s.Init != nil {
			g.stmt(s.Init)
		}
		c := g.expr(s.Cond)
		g.line("if (%s)", c)
		g.block(s.Body)
		if s.Else != nil {
			g.line("else")
			g.stmt(s.Else)
		}
		g.line("}")
	case *ast.ForStmt:
		g.loop(s)
	case *ast.RangeStmt:
		g.rangeLoop(s)
	case *ast.SwitchStmt:
		g.switchStatement(s)
	case *ast.TypeSwitchStmt:
		g.typeSwitch(s)
	case *ast.IncDecStmt:
		if ix, ok := g.isMapIndex(s.X); ok {
			g.mapIncDec(ix, s.Tok.String())
			return
		}
		id, ok := s.X.(*ast.Ident)
		t := g.info.Types[s.X].Type
		if !ok {
			target := g.captureTarget(s.X)
			if isSigned(t) {
				g.incDec(s, t, "("+target+")", s.Tok.String())
				return
			}
			g.line("(%s)%s;", target, s.Tok)
			return
		}
		if isSigned(t) {
			g.incDec(s, t, g.name(g.info.Uses[id]), s.Tok.String())
			return
		}
		g.line("%s%s;", g.name(g.info.Uses[id]), s.Tok)
	case *ast.BranchStmt:
		if s.Label != nil {
			g.unchecked(s)
		}
		switch s.Tok {
		case token.BREAK:
			g.line("break;")
		case token.CONTINUE:
			if len(g.continueLabels) == 0 {
				g.unchecked(s)
			}
			g.line("goto %s;", g.continueLabels[len(g.continueLabels)-1])
		default:
			g.unchecked(s)
		}
	case *ast.DeferStmt:
		g.deferStmt(s)
	case *ast.EmptyStmt:
	default:
		g.unchecked(s)
	}
}

// valueSpec declares the variables of one var specification.
func (g *generator) valueSpec(v *ast.ValueSpec) {
	if len(v.Names) != 1 || len(v.Values) > 1 {
		g.multiDeclaration(v)
		return
	}
	o := g.info.Defs[v.Names[0]]
	rhs := "{0}"
	if len(v.Values) == 1 {
		rhs = g.exprAs(v.Values[0], o.Type())
		if _, ok := o.Type().Underlying().(*types.Array); ok && !g.moved[o] {
			g.names[o] = rhs
			return
		}
	}
	if g.moved[o] {
		g.declareMoved(v, o, rhs)
		return
	}
	g.line("%s %s = %s;", g.variable(v, o.Type()), g.name(o), rhs)
}

// Targets preserve storage identity. Pointer operands are saved now; the
// returned target performs its nil check at the later load/address/store.
func (g *generator) fieldTarget(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		return g.name(g.info.Uses[e])
	case *ast.ParenExpr:
		return g.fieldTarget(e.X)
	case *ast.StarExpr:
		return "(*" + g.checkedPointer(e, g.info.Types[e.X].Type, g.expr(e.X)) + ")"
	case *ast.SelectorExpr:
		if v := g.packageVar(e); v != nil {
			return g.name(v) // pkg.V
		}
		f, ok := g.info.Uses[e.Sel].(*types.Var)
		if !ok || !f.IsField() {
			g.unchecked(e)
		}
		if p, ok := pointer(g.info.Types[e.X].Type); ok {
			return g.checkedPointer(e, p, g.expr(e.X)) + "->" + g.name(f)
		}
		return g.fieldTarget(e.X) + "." + g.name(f)
	case *ast.IndexExpr:
		t := g.info.Types[e.X].Type
		if a, ok := arrayValue(t); ok {
			// Array storage (or an array through a pointer): the base is
			// saved now and the bounds (and nil) check runs at the use.
			base, index := g.arrayPointer(e.X), g.expr(e.Index)
			return fmt.Sprintf("(*%s_at(%s,%s))", g.arrayName(e, a), base, index)
		}
		if _, ok := t.(*types.Slice); !ok {
			g.unchecked(e)
		}
		x, i := g.expr(e.X), g.expr(e.Index)
		if isByteSlice(t) {
			return fmt.Sprintf("(*at(%s,%s))", x, i)
		}
		return g.element(e, t, x, i)
	default:
		g.unchecked(e)
	}
	return ""
}
