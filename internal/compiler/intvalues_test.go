// intType is one integer type of the examples/int-values fixture.
type intType struct {
	name   string // Go type name
	width  int
	signed bool
}

// intTypes are every integer type of the subset plus named versions. The
// fixture's Eval dispatches on the index in this list.
var intTypes = []intType{
	{"int8", 8, true}, {"int16", 16, true}, {"int32", 32, true}, {"int64", 64, true}, {"int", 64, true},
	{"uint8", 8, false}, {"uint16", 16, false}, {"uint32", 32, false}, {"uint64", 64, false}, {"uint", 64, false},
	{"I16", 16, true}, {"N", 64, true}, {"W", 64, false},
}

// Shift counts may have any integer type.
var intCountTypes = []string{"int8", "int16", "int32", "int64", "int", "uint8", "uint16", "uint32", "uint64", "uint"}

// Operation numbers per type; see intValuesSource.
const (
	intOpShl      = 20
	intOpShr      = intOpShl + 10
	intOpConvert  = intOpShr + 10
	intOpSwitch   = intOpConvert + 13
	intOpRange    = intOpSwitch + 1
	intOpPointer  = intOpRange + 1
	intOpConstant = intOpPointer + 1
	intOpStorage  = intOpConstant + 1
	intOpMixed    = intOpStorage + 1
	intOpDivMod   = intOpMixed + 1
	intOpShiftK   = intOpDivMod + 1
	intOpLoop     = intOpShiftK + 1
	intOps        = intOpLoop + 1
)

func (t intType) bounds() (min, max string) {
	if !t.signed {
		return "0", fmt.Sprint(^uint64(0) >> (64 - t.width))
	}
	return fmt.Sprint(-int64(1) << (t.width - 1)), fmt.Sprint(int64(^uint64(0) >> (65 - t.width)))
}

func (t intType) ident() string { return strings.ToUpper(t.name[:1]) + t.name[1:] }

// The storage case avoids uint64(v*3) ^ uint64(v)<<k for a uint32 v: Go
// 1.22.0 on darwin/arm64 miscompiles that expression with optimization on
// (v = 0xffffffff gives 0x0000fffd0000fffd for k = 16), which would make the
// native oracle, not the compiler, wrong.

// intValuesSource generates examples/int-values/ops.go: for every integer
// type, every operator, conversion, shift-count type and storage form, as
// ordinary Go that the native tests run with real Go and the compiler lowers
// to C and SBF.
func intValuesSource() string {
	var b strings.Builder
	b.WriteString(`// Code generated by TestIntValuesFixture (internal/compiler/intvalues_test.go). DO NOT EDIT.

package intvalues

type I16 int16
type N int
type W uint

func cmp(b bool) uint64 {
	if b {
		return 1
	}
	return 0
}

// Eval applies operation code&255 of integer type code>>8 to a and b.
func Eval(code, a, b uint64) uint64 {
	op := code & 255
	switch code >> 8 {
`)
	for n, t := range intTypes {
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn ops%s(op, a, b)\n", n, t.ident())
	}
	b.WriteString("\t}\n\treturn 0\n}\n")
	for _, t := range intTypes {
		T, id := t.name, t.ident()
		min, max := t.bounds()
		fmt.Fprintf(&b, "\ntype box%s struct {\n\tV %s\n\tA [3]%s\n}\n", id, T, T)
		fmt.Fprintf(&b, "\nfunc divmod%s(x, y %s) (%s, %s) { return x / y, x %% y }\n", id, T, T, T)
		fmt.Fprintf(&b, "\nfunc ops%s(op, a, b uint64) uint64 {\n\tx, y := %s(a), %s(b)\n\tswitch op {\n", id, T, T)
		cases := []string{"x + y", "x - y", "x * y", "x / y", "x % y", "x & y", "x | y", "x ^ y", "x &^ y", "-x", "^x", "+x"}
		for n, c := range cases {
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(%s)\n", n, c)
		}
		for n, op := range []string{"<", "<=", ">", ">=", "==", "!="} {
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn cmp(x %s y)\n", 12+n, op)
		}
		fmt.Fprintf(&b, "\tcase 18:\n\t\tx++\n\t\treturn uint64(x)\n\tcase 19:\n\t\tx--\n\t\treturn uint64(x)\n")
		for n, c := range intCountTypes {
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(x << %s(b))\n", intOpShl+n, c)
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(x >> %s(b))\n", intOpShr+n, c)
		}
		for n, u := range intTypes {
			fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(%s(x))\n", intOpConvert+n, u.name)
		}
		fmt.Fprintf(&b, "\tcase %d:\n\t\tswitch x {\n", intOpSwitch)
		if t.signed {
			fmt.Fprintf(&b, "\t\tcase -1:\n\t\t\treturn 1\n\t\tcase 0, 1:\n\t\t\treturn 2\n\t\tcase %s:\n\t\t\treturn 3\n\t\tcase %s:\n\t\t\treturn 4\n", max, min)
		} else {
			fmt.Fprintf(&b, "\t\tcase 0, 1:\n\t\t\treturn 2\n\t\tcase %s:\n\t\t\treturn 3\n", max)
		}
		b.WriteString("\t\tcase y:\n\t\t\treturn 5\n\t\t}\n\t\treturn 6\n")
		fmt.Fprintf(&b, "\tcase %d:\n\t\tn := x %% 9\n\t\ts := uint64(0)\n\t\tfor i := range n {\n\t\t\ts = s*3 + uint64(i) + 1\n\t\t}\n\t\treturn s\n", intOpRange)
		fmt.Fprintf(&b, "\tcase %d:\n\t\tp := &x\n\t\t*p = *p + y\n\t\t*p++\n\t\treturn uint64(*p)\n", intOpPointer)
		if t.signed {
			fmt.Fprintf(&b, "\tcase %d:\n\t\tconst low, high %s = %s, %s\n\t\treturn uint64(x*-3+7-y/(-2)) ^ cmp(x == low)<<60 ^ cmp(y != high)<<61 ^ cmp(x < -1)<<62\n", intOpConstant, T, min, max)
		} else {
			fmt.Fprintf(&b, "\tcase %d:\n\t\tconst high %s = %s\n\t\treturn uint64(x*3+7-y/2) ^ cmp(y != high)<<61 ^ cmp(x < 1)<<62\n", intOpConstant, T, max)
		}
		fmt.Fprintf(&b, "\tcase %d:\n\t\tvar bx box%s\n\t\tbx.V = x\n\t\tbx.A[1] = y\n\t\tbx.A[2] = bx.V - bx.A[1]\n\t\tbx.A[0]--\n\t\tp := &bx.A[2]\n\t\t*p = *p + bx.A[1]\n\t\treturn uint64(bx.A[2]) ^ uint64(bx.A[0])<<8 ^ uint64(bx.V)<<16\n", intOpStorage, id)
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(int64(x)*int64(y)+int64(int8(x))-int64(uint8(y))) ^ uint64(int32(x)/(int32(y)|1))\n", intOpMixed)
		fmt.Fprintf(&b, "\tcase %d:\n\t\tq, r := divmod%s(x, y)\n\t\treturn uint64(q)*31 + uint64(r)\n", intOpDivMod, id)
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn uint64(x>>%d) ^ uint64(x<<%d)<<1 ^ uint64(x>>1)<<2\n", intOpShiftK, t.width-1, t.width-1)
		fmt.Fprintf(&b, "\tcase %d:\n\t\ts := %s(0)\n\t\tfor k := %s(0); k < 5; k++ {\n\t\t\ts = s*y + x\n\t\t}\n\t\treturn uint64(s)\n", intOpLoop, T, T)
		b.WriteString("\t}\n\treturn 0\n}\n")
	}
	return b.String()
}

const (
	intValuesOps     = "../../examples/int-values/ops.go"
	intValuesProgram = "../../examples/int-values/program.go"
)

// The checked-in fixture is the generator's output. Set
// GOSVM_UPDATE_INT_VALUES=1 to rewrite it.
func TestIntValuesFixture(t *testing.T) {
	want := []byte(intValuesSource())
	if os.Getenv("GOSVM_UPDATE_INT_VALUES") == "1" {
		if err := os.WriteFile(intValuesOps, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(intValuesOps)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("examples/int-values/ops.go is stale (GOSVM_UPDATE_INT_VALUES=1 regenerates it): %v", err)
	}
	if _, err := Check(&Program{Entry: "program", Packages: []PackageSources{{"program", intValuesSources(t)}}}); err != nil {
		t.Fatal(err)
	}
}

func intValuesSources(t *testing.T) []Source {
	t.Helper()
	var sources []Source
	for _, path := range []string{intValuesOps, intValuesProgram} {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		sources = append(sources, Source{Name: path[strings.LastIndex(path, "/")+1:], Data: data})
	}
	return sources
}

// intEdges are boundary values of a type as 64-bit inputs: 0, ±1, ±2, min,
// max and their neighbours, powers of two and their neighbours (sign-extended
// for signed types), and raw 64-bit patterns that the conversion to the type
// truncates.
func intEdges(t intType) []uint64 {
	mask := ^uint64(0) >> (64 - t.width)
	extend := func(v uint64) uint64 {
		v &= mask
		if t.signed && t.width < 64 && v>>(t.width-1) != 0 {
			v |= ^mask
		}
		return v
	}
	set := map[uint64]bool{}
	var out []uint64
	add := func(v uint64) {
		if !set[v] {
			set[v] = true
			out = append(out, v)
		}
	}
	for _, v := range []uint64{0, 1, 2, 3, 7, 9, 100, ^uint64(0), ^uint64(0) - 1, ^uint64(0) - 6, mask, mask >> 1, mask>>1 + 1, mask>>1 + 2, mask>>1 - 1} {
		add(extend(v))
	}
	for s := 1; s < t.width; s += 3 {
		add(extend(uint64(1) << s))
		add(extend(uint64(1)<<s - 1))
		add(extend(-(uint64(1) << s)))
	}
	// Raw inputs whose high bits the conversion discards.
	add(0x0123456789abcdef)
	add(0xfedcba9876543210)
	add(mask + 1)
	add(1 << 63)
	return out
}

// intCounts are shift-count inputs (converted to each count type): within,
// at and beyond every width, and negative.
var intCounts = []uint64{0, 1, 2, 7, 8, 9, 15, 16, 17, 31, 32, 33, 62, 63, 64, 65, 127, 128, 255, 256, 257, 1 << 32, 1<<32 + 3, 1 << 63, 1<<63 - 1,
	^uint64(0), ^uint64(0) - 1, ^uint64(7 - 1), ^uint64(8 - 1), ^uint64(63 - 1), ^uint64(64 - 1), ^uint64(65 - 1), ^uint64(128 - 1), ^uint64(129 - 1), ^uint64(256 - 1)}

type intVector struct{ code, a, b uint64 }

// intVectors covers every operation of every type with edge × edge operands
// (edge × count for shifts) and random operands.
func intVectors(random int) []intVector {
	rng := rand.New(rand.NewSource(20261014))
	var vectors []intVector
	for n, t := range intTypes {
		edges := intEdges(t)
		pick := func() uint64 {
			switch rng.Intn(3) {
			case 0:
				return rng.Uint64()
			case 1:
				return rng.Uint64() >> uint(rng.Intn(64))
			}
			return edges[rng.Intn(len(edges))]
		}
		for op := 0; op < intOps; op++ {
			code := uint64(n)<<8 | uint64(op)
			counts := edges
			if op >= intOpShl && op < intOpConvert {
				counts = intCounts
			}
			for _, a := range edges {
				for _, b := range counts {
					vectors = append(vectors, intVector{code, a, b})
				}
			}
			for j := 0; j < random; j++ {
				b := pick()
				if op >= intOpShl && op < intOpConvert && j%2 == 0 {
					b = intCounts[rng.Intn(len(intCounts))]
				}
				vectors = append(vectors, intVector{code, pick(), b})
			}
		}
	}
	return vectors
}

// intReference is the native Go result, or "P" where Go panics.
func intReference(v intVector) (out string) {
	defer func() {
		if recover() != nil {
			out = "P"
		}
	}()
	return fmt.Sprintf("%016x", intvalues.Eval(v.code, v.a, v.b))
}

// The driver runs one vector per input line through the legacy entry (state
// a, b, result; instruction code, status); abort longjmps back and prints "P".
const intHostDriver = `
#include <setjmp.h>
#include <stdio.h>
static jmp_buf int_trap;
void abort(void) { longjmp(int_trap, 1); }
int main(void) {
    unsigned long long code, a, b;
    u8 state[24], ix[16];
    while (scanf("%llx %llx %llx", &code, &a, &b) == 3) {
        for (int j = 0; j < 8; j++) {
            state[j] = (u8)(a >> (8*j)); state[8+j] = (u8)(b >> (8*j)); state[16+j] = 0;
            ix[j] = (u8)(code >> (8*j)); ix[8+j] = 0;
        }
        if (setjmp(int_trap)) { puts("P"); continue; }
        go_Process(GOSVM_SLICE(state, 24), GOSVM_SLICE(ix, 16));
        u64 r = 0;
        for (int j = 7; j >= 0; j--) r = r<<8 | state[16+j];
        printf("%016llx\n", r);
    }
    return 0;
}`

// TestIntValuesDifferential compiles the fixture to C with the host compiler
// and compares every vector with ordinary Go, including the traps: division
// and remainder by zero and negative shift counts abort exactly where Go
// panics, and MinInt / -1 and MinInt % -1 do not.
func TestIntValuesDifferential(t *testing.T) {
	bin := hostSources(t, intValuesSources(t), intHostDriver)
	vectors := intVectors(300)
	var input strings.Builder
	want := make([]string, len(vectors))
	panics := map[string]int{}
	minByMinusOne := 0
	for j, v := range vectors {
		if ty := intTypes[v.code>>8]; ty.signed && (v.code&255 == 3 || v.code&255 == 4) && v.b == ^uint64(0) {
			if min := ^uint64(0) << (ty.width - 1); v.a == min {
				minByMinusOne++
			}
		}
		fmt.Fprintf(&input, "%x %x %x\n", v.code, v.a, v.b)
		want[j] = intReference(v)
		if want[j] == "P" {
			op := int(v.code & 255)
			switch {
			case op == 3 || op == 4 || op == intOpDivMod:
				panics["division"]++
			case op >= intOpShl && op < intOpConvert:
				panics["shift"]++
			default:
				t.Fatalf("unexpected Go panic for %+v", v)
			}
		}
	}
	cmd := exec.Command(bin)
	cmd.Stdin = strings.NewReader(input.String())
	got, err := cmd.Output()
	if err != nil {
		t.Fatalf("host binary: %v", err)
	}
	lines := bufio.NewScanner(bytes.NewReader(got))
	j, mismatches := 0, 0
	for ; lines.Scan(); j++ {
		if j >= len(want) {
			t.Fatalf("extra output %q", lines.Text())
		}
		if lines.Text() != want[j] {
			if mismatches++; mismatches <= 20 {
				v := vectors[j]
				ty := intTypes[v.code>>8]
				t.Errorf("%s op %d (%#x, %#x): C %s, Go %s", ty.name, v.code&255, v.a, v.b, lines.Text(), want[j])
			}
		}
	}
	if j != len(want) {
		t.Fatalf("output truncated at %d of %d", j, len(want))
	}
	if mismatches != 0 {
		t.Fatalf("%d of %d vectors differ", mismatches, len(want))
	}
	// MinInt / -1 == MinInt and MinInt % -1 == 0 for each signed type, untrapped.
	if minByMinusOne < 2*7 {
		t.Fatalf("only %d MinInt/-1 vectors", minByMinusOne)
	}
	if panics["division"] == 0 || panics["shift"] == 0 {
		t.Fatalf("vectors must include both trap kinds: %v", panics)
	}
	t.Logf("%d vectors over %d types × %d operations agree with Go (%d division and %d negative-shift traps)", len(vectors), len(intTypes), intOps, panics["division"], panics["shift"])
}
