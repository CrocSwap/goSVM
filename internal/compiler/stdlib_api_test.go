package compiler

import (
	"bufio"
	"fmt"
	"go/build"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// apiLine matches a line of $GOROOT/api/go1*.txt for a platform-independent
// package: "pkg strings, func Map(...)", "pkg strings, method (*Builder)
// Grow(int)", "pkg math, const MaxInt ideal-int", "pkg strings, type Builder
// struct".
var apiLine = regexp.MustCompile(`^pkg ([a-z0-9/]+), (func|method|const|var|type) (?:\((\*?)([A-Za-z0-9_]+)\) )?([A-Za-z0-9_]+)`)

// goStdlibAPI derives _stdlib/api.txt from the host toolchain's API files.
func goStdlibAPI(t *testing.T) string {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(build.Default.GOROOT, "api", "go1*.txt"))
	if err != nil || len(files) == 0 {
		t.Fatalf("no API files under %s: %v", build.Default.GOROOT, err)
	}
	seen := map[string]string{}
	for _, name := range files {
		f, err := os.Open(name)
		if err != nil {
			t.Fatal(err)
		}
		s := bufio.NewScanner(f)
		for s.Scan() {
			m := apiLine.FindStringSubmatch(s.Text())
			if m == nil || !stdlibPackage(m[1]) {
				continue
			}
			kind, symbol := m[2], m[5]
			if kind == "method" {
				symbol = m[4] + "." + m[5]
			}
			if kind == "type" && strings.Contains(s.Text(), ", type "+m[5]+" struct, ") {
				continue // a field
			}
			if kind == "type" && regexp.MustCompile(`, type `+m[5]+` interface, [A-Z]`).MatchString(s.Text()) {
				continue // an interface method
			}
			seen[m[1]+" "+symbol] = kind
		}
		f.Close()
	}
	var lines []string
	for k, kind := range seen {
		lines = append(lines, k+" "+kind)
	}
	sort.Strings(lines)
	return fmt.Sprintf("# Go %s exported API of the overlay packages, from $GOROOT/api/go1*.txt.\n# Generated by TestStdlibAPI (GOSVM_UPDATE_STDLIB=1 rewrites it).\n%s\n", StdlibVersion, strings.Join(lines, "\n"))
}

// TestStdlibAPI checks _stdlib/api.txt against the host Go 1.22.0 API files.
func TestStdlibAPI(t *testing.T) {
	want := goStdlibAPI(t)
	if os.Getenv("GOSVM_UPDATE_STDLIB") != "" {
		if err := os.WriteFile("_stdlib/api.txt", []byte(want), 0644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("_stdlib/api.txt")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatal("_stdlib/api.txt differs from the host toolchain's API; rerun with GOSVM_UPDATE_STDLIB=1")
	}
}
