package library

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

// Generate binds an already agreed artifact contract; it never rebuilds or
// re-labels Bend objects and never assumes that a v3 artifact exists.
func GenerateBend(manifest, digest, pkg, function, allowedTools, output string) error {
	b, err := ImportBend(manifest, digest, pkg, function, allowedTools)
	if err != nil {
		return err
	}
	if len(b.Generated) != 0 {
		return fmt.Errorf("bind a producer contract, not an already generated package")
	}
	if _, err = os.Lstat(output); err == nil {
		return fmt.Errorf("%s already exists", output)
	} else if !os.IsNotExist(err) {
		return err
	}
	if err = os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	stage, err := os.MkdirTemp(filepath.Dir(output), ".gosvm-library-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	for path, data := range b.Metadata {

		rel, err := filepath.Rel(b.Dir, path)
		if err != nil {
			return err
		}
		dest := filepath.Join(stage, rel)
		if err = os.MkdirAll(filepath.Dir(dest), 0755); err != nil {
			return err
		}
		if err = os.WriteFile(dest, data, 0644); err != nil {
			return err
		}
	}
	// Cgo synchronously borrows byte-only slices. output_len is aligned owned
	// scalar storage, separate from both input/output; no pointer is retained.
	goSource, err := nativeSource(b.Contract)
	if err != nil {
		return err
	}
	b.Generated = map[string]string{"bindings.go": fmt.Sprintf("%x", sha256.Sum256(goSource))}
	if err = os.WriteFile(filepath.Join(stage, "bindings.go"), goSource, 0644); err != nil {
		return err
	}
	data, err := json.MarshalIndent(b.Contract, "", "  ")
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(stage, Filename), append(data, '\n'), 0644); err != nil {
		return err
	}
	return os.Rename(stage, output)
}

func nativeSource(c Contract) ([]byte, error) {
	b := Binding{Contract: c}
	source := fmt.Sprintf(`// Code generated by gosvm library bind. DO NOT EDIT.
package %s
/*
#cgo LDFLAGS: ${SRCDIR}/%s
#include <stdint.h>
#include "%s"
*/
import "C"
import "unsafe"
import "runtime"
const InputBytes uint64=%d
const OutputBytes uint64=%d
const ABI_OK uint32=0
const ABI_NULL uint32=1
const ABI_RANGE uint32=2
const ABI_ALIAS uint32=3
const ABI_MALFORMED_INPUT uint32=4
const ABI_SHORT_OUTPUT uint32=5
const ABI_MISALIGNED_OUTPUT_LEN uint32=6
const ABI_OUTPUT_ENCODING uint32=7
func %s(input,output []byte)(uint32,uint64) {
 var length C.uint64_t
 code:=C.%s((*C.uint8_t)(unsafe.Pointer(unsafe.SliceData(input))),C.uint64_t(len(input)),(*C.uint8_t)(unsafe.Pointer(unsafe.SliceData(output))),C.uint64_t(len(output)),&length)
 runtime.KeepAlive(input);runtime.KeepAlive(output)
 return uint32(code),uint64(length)
}
`, b.Package, b.Host.Object.Path, b.Header.Path, b.InputBytes, b.OutputBytes, b.Function, b.Symbol)
	goSource, err := format.Source([]byte(source))
	if err != nil {
		return nil, err
	}
	return goSource, nil
}
