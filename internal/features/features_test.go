func report(t *testing.T, path string) *Usage {
	t.Helper()
	program, err := compiler.ReadProgram(path)
	if err != nil {
		t.Fatal(err)
	}
	tp, err := compiler.TypeCheckProgram(program)
	if err != nil {
		t.Fatal(err)
	}
	u, err := Report(tp)
	if err != nil {
		t.Fatal(err)
	}
	return u
}

const handwritten = `package program

import "gosvm/solana"

const Limit uint64 = 8
const Untyped = 3

type Pair struct {
	A, B uint64
}

type Key [4]byte

func (p *Pair) Bump() { p.A++ }

func (p Pair) Sum() uint64 { return p.A + p.B }

func split(x uint64) (uint64, uint64) { return x >> 1, x & 1 }

func Process(c solana.Context) uint64 {
	var p Pair
	q := &p
	q.Bump()
	k := Key{1, 2, 3, 4}
	if k == (Key{}) {
		return 1
	} else if k[0] != 1 {
		return 2
	}
	view := k[:]
	total := uint64(len(view))
	for i := uint64(0); i < Limit; i++ {
		for total < 100 {
			total += i
		}
		if i == 5 {
			break
		}
	}
	for {
		total--
		if total < 10 {
			break
		}
	}
	for range k {
		continue
	}
	switch total {
	case 1, 2:
		total = 3
	default:
	}
	h, l := split(total)
	_ = solana.Count(c)
	_ = solana.Count(c)
	return (*q).Sum() + h + l + Untyped
}
`

const generated = `// Code generated by test. DO NOT EDIT.

package program

import "gosvm/solana"

func Adapter(c solana.Context) uint64 {
	if !solana.Signer(c, 0) {
		return 1
	}
	return Process(c)
}
`

func TestInlineProgram(t *testing.T) {
	dir := t.TempDir()
	for name, src := range map[string]string{"program.go": handwritten, "zz_gen.go": generated} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0644); err != nil {
			t.Fatal(err)
		}
	}
	u := report(t, dir)
	if u.Schema != Schema || u.Program.EntryPackage != "program" || len(u.Files) != 2 {
		t.Fatalf("identity: %+v %+v", u.Program, u.Files)
	}
	if u.Files[0].Path != "program.go" || u.Files[0].Kind != Handwritten || u.Files[1].Kind != Generated || len(u.Files[0].SHA256) != 64 {
		t.Fatalf("files: %+v", u.Files)
	}
	if u.Lines.Handwritten != strings.Count(handwritten, "\n") || u.Lines.Generated != strings.Count(generated, "\n") {
		t.Fatalf("lines: %+v", u.Lines)
	}
	h := u.Language.Handwritten
	want := map[string]int{
		"functions": 2, "methods_declared": 2, "pointer_receivers": 1, "value_receivers": 1, "multi_result_functions": 1,
		"struct_type_decls": 1, "array_type_decls": 1, "struct_literals": 0, "array_literals": 2, "array_equality": 1,
		"slice_expressions": 1, "slice_expressions_of_arrays": 1, "address_of": 1, "pointer_derefs": 1,
		"method_calls": 2, "function_calls": 1, "sdk_calls": 2, "builtin_calls": 1, "conversions": 2,
		"for_three_clause": 1, "for_condition_only": 1, "for_infinite": 1, "for_range": 1, "for_range_array": 1,
		"break": 2, "continue": 1, "switch": 1, "switch_cases": 2, "if": 3, "else": 0, "else_if": 1,
		"const_typed": 1, "const_untyped": 1, "multi_value_assignments": 1, "multi_value_returns": 1, "compound_assignments": 1,
	}
	for k, v := range want {
		if h.Constructs[k] != v {
			t.Errorf("handwritten %s = %d, want %d", k, h.Constructs[k], v)
		}
	}
	if h.MaxLoopNesting != 2 || h.Builtins["len"] != 1 || h.Conversions["uint64"] != 2 {
		t.Errorf("nesting/builtins/conversions: %d %v %v", h.MaxLoopNesting, h.Builtins, h.Conversions)
	}
	for op, n := range map[string]int{">>": 1, "&": 1, "++": 2, "--": 1, "+=": 1, "==": 2, "!=": 1, "<": 3} {
		if h.Operators[op] != n {
			t.Errorf("operator %s = %d, want %d (%v)", op, h.Operators[op], n, h.Operators)
		}
	}
	if len(h.Arrays) != 1 || h.Arrays[0].Type != "[4]byte" || h.Arrays[0].Length != 4 || h.Arrays[0].Elem != "byte" {
		t.Errorf("arrays: %+v", h.Arrays)
	}
	if h.IntegerTypes["uint64"] == 0 || h.IntegerTypes["byte"] != 1 || h.IntegerValues["int"] == 0 {
		t.Errorf("integer types: %v values %v", h.IntegerTypes, h.IntegerValues)
	}
	g := u.Language.Generated
	if g.Constructs["functions"] != 1 || g.Constructs["function_calls"] != 1 || g.Operators["!"] != 1 || g.Files != 1 {
		t.Errorf("generated: %+v", g)
	}
	if len(u.SDKCalls) != 2 {
		t.Fatalf("sdk calls: %+v", u.SDKCalls)
	}
	count, signer := u.SDKCalls[0], u.SDKCalls[1]
	if count.Name != "gosvm/solana.Count" || count.Count != 2 || count.Handwritten != 2 || len(count.Positions) != 2 || !strings.HasPrefix(count.Positions[0], "program.go:") {
		t.Errorf("count: %+v", count)
	}
	if signer.Name != "gosvm/solana.Signer" || signer.Generated != 1 || signer.Positions[0] != "zz_gen.go:8" {
		t.Errorf("signer: %+v", signer)
	}
}

func fullSwap(t *testing.T) *Usage {
	u := report(t, filepath.Join("..", "..", "examples", "full-swap"))
	return u
}

func TestFullSwapFacts(t *testing.T) {
	u := fullSwap(t)
	if u.Program.EntryPackage != "example.org/gosvm/full-swap" {
		t.Fatalf("entry: %s", u.Program.EntryPackage)
	}
	kinds := map[string]string{}
	for _, f := range u.Files {
		kinds[f.Path] = f.Kind
	}
	if kinds["zz_gosvm.go"] != Generated || kinds["program.go"] != Handwritten || kinds["lifecycle.go"] != Handwritten || kinds["model/quote.go"] != Handwritten {
		t.Fatalf("file kinds: %v", kinds)
	}
	calls := map[string]CallSite{}
	for _, c := range u.SDKCalls {
		calls[c.Name] = c
		if c.Count != c.Handwritten+c.Generated || len(c.Positions) != c.Count {
			t.Errorf("inconsistent call site %+v", c)
		}
	}
	for _, name := range []string{"gosvm/sdk/token.Transfer", "gosvm/sdk/token.TransferSigned", "gosvm/sdk/token.CreateSigned",
		"gosvm/sdk/token.CloseSigned", "gosvm/sdk/token.Balance", "gosvm/sdk/token.Load",
		"(*gosvm/sdk/pda.Seeds).AddBytes", "(*gosvm/sdk/pda.Seeds).AddKey", "(*gosvm/sdk/pda.Seeds).AddByte"} {
		if calls[name].Handwritten == 0 {
			t.Errorf("handwritten code should call %s: %+v", name, calls[name])
		}
	}
	for _, name := range []string{"gosvm/sdk/system.Create", "gosvm/solana.CloseAccount", "(*gosvm/sdk/pda.Seeds).Matches"} {
		if calls[name].Generated == 0 || calls[name].Handwritten != 0 {
			t.Errorf("only generated code should call %s: %+v", name, calls[name])
		}
	}
	for name := range calls {
		if strings.Contains(name, "Clock") || strings.Contains(name, "ReturnData") || strings.Contains(name, "Rent") {
			t.Errorf("unexpected sysvar/return-data call %s", name)
		}
	}
	h := u.Language.Handwritten
	for _, m := range []map[string]int{h.IntegerTypes, h.IntegerValues} {
		for name := range m {
			if name != "byte" && name != "uint64" {
				t.Errorf("handwritten integer type %s: %v", name, m)
			}
		}
	}
	if h.Constructs["sdk_calls"] != 30 || u.Lines.Generated == 0 || u.Lines.Handwritten == 0 {
		t.Errorf("totals: %d %+v", h.Constructs["sdk_calls"], u.Lines)
	}
}

func TestDeterministicOutput(t *testing.T) {
	a, err := Marshal(fullSwap(t))
	if err != nil {
		t.Fatal(err)
	}
	b, err := Marshal(fullSwap(t))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("report bytes differ between runs")
	}
}

func TestStdlibCalls(t *testing.T) {
	dir := t.TempDir()
	src := `package program

import wide "math/bits"

func Process(s, i []byte) uint64 {
	hi, lo := wide.Mul64(uint64(len(s)), 3)
	q, _ := wide.Div64(0, lo, 7)
	return hi + q + uint64(wide.LeadingZeros64(lo)) + wide.UintSize
}
`
	if err := os.WriteFile(filepath.Join(dir, "program.go"), []byte(src), 0644); err != nil {
		t.Fatal(err)
	}
	u := report(t, dir)
	if len(u.SDKCalls) != 0 || len(u.StdlibCalls) != 3 {
		t.Fatalf("stdlib calls: %+v sdk %+v", u.StdlibCalls, u.SDKCalls)
	}
	div := u.StdlibCalls[0]
	if div.Name != "math/bits.Div64" || div.Package != "math/bits" || div.Count != 1 || div.Handwritten != 1 || div.Positions[0] != "program.go:7" {
		t.Errorf("div64: %+v", div)
	}
	h := u.Language.Handwritten
	if h.Constructs["cross_package_calls"] != 3 || h.Constructs["sdk_calls"] != 0 || len(h.Imports) != 1 || h.Imports[0] != "math/bits" {
		t.Errorf("constructs: %v imports %v", h.Constructs["cross_package_calls"], h.Imports)
	}
	if fs := fullSwap(t); fs.StdlibCalls == nil || len(fs.StdlibCalls) != 0 {
		t.Errorf("full swap must report an empty stdlib_calls list: %+v", fs.StdlibCalls)
	}
}

// Signed integer types and uint are reported like every integer type; signed
// division and non-constant signed shift counts (which can trap on a negative
// count) have their own counters.
func TestSignedIntegers(t *testing.T) {
	dir := t.TempDir()
	src := `package main

type Tick int16

func Process(s, i []byte) uint64 {
	var a int8 = -3
	b := int64(i[0]) - 7
	var u uint = 9
	n := len(s)
	c := Tick(b) / 2
	d := b % int64(a)
	e := u >> n
	f := b << 3
	g := a / 2
	_ = 7 / 2
	return uint64(c) + uint64(d) + uint64(e) + uint64(f) + uint64(g)
}
`
	if err := os.WriteFile(filepath.Join(dir, "program.go"), []byte(src), 0644); err != nil {
		t.Fatal(err)
	}
	h := report(t, dir).Language.Handwritten
	for _, name := range []string{"int8", "int64", "uint"} {
		if h.IntegerTypes[name] == 0 || h.IntegerValues[name] == 0 {
			t.Errorf("integer type %s: types %v values %v", name, h.IntegerTypes, h.IntegerValues)
		}
	}
	if h.IntegerValues["int16"] == 0 || h.IntegerValues["int"] == 0 {
		t.Errorf("named int16 and len results: %v", h.IntegerValues)
	}
	if h.Constructs["signed_division"] != 3 || h.Constructs["signed_shift_counts"] != 1 {
		t.Errorf("signed_division %d, signed_shift_counts %d", h.Constructs["signed_division"], h.Constructs["signed_shift_counts"])
	}
}

func TestGenerics(t *testing.T) {
	dir := t.TempDir()
	src := `package program

type Unsigned interface{ ~uint8 | ~uint64 }

type Box[T any] struct{ V T }

func (b *Box[T]) Set(v T) { b.V = v }

func Min[T Unsigned](a, b T) T {
	if a < b {
		return a
	}
	return b
}

func Clamp[T Unsigned](x, hi T) T { return Min(x, hi) }

func Unused[A, B any](a A, b B) {}

func Process(s, i []byte) uint64 {
	var b Box[uint64]
	b.Set(Clamp(uint64(len(s)), 9))
	return b.V + uint64(Min[byte](s[0], s[1]))
}
`
	if err := os.WriteFile(filepath.Join(dir, "program.go"), []byte(src), 0644); err != nil {
		t.Fatal(err)
	}
	u := report(t, dir)
	h := u.Language.Handwritten
	for name, want := range map[string]int{"generic_functions": 3, "generic_methods": 1, "generic_types": 1, "type_parameters": 5,
		"explicit_instantiations": 1, "inferred_instantiations": 2, "type_instantiations": 2, "indirect_calls": 0, "index_expressions": 2, "function_calls": 3} {
		if h.Constructs[name] != want {
			t.Errorf("%s: %d, want %d", name, h.Constructs[name], want)
		}
	}
	got := map[string]GenericUse{}
	for _, g := range u.Generics {
		got[g.Name] = g
	}
	want := map[string][]string{
		"program.Box":     {"program.Box[uint64]"},
		"program.Box.Set": {"program.Box[uint64].Set"},
		"program.Min":     {"program.Min[uint64]", "program.Min[uint8]"},
		"program.Clamp":   {"program.Clamp[uint64]"},
		"program.Unused":  {},
	}
	if len(got) != len(want) {
		t.Fatalf("generics: %+v", u.Generics)
	}
	for name, instances := range want {
		g := got[name]
		if g.Count != len(instances) || !reflect.DeepEqual(g.Instances, instances) || g.Package != "program" {
			t.Errorf("%s: %+v, want %q", name, g, instances)
		}
	}
	if got["program.Box.Set"].Kind != "method" || got["program.Box"].Kind != "type" || got["program.Min"].Kind != "function" {
		t.Errorf("kinds: %+v", u.Generics)
	}
	if fs := fullSwap(t); fs.Generics == nil || len(fs.Generics) != 0 || fs.Language.Handwritten.Constructs["type_parameters"] != 0 {
		t.Errorf("full swap must report an empty generics list: %+v", fs.Generics)
	}
}

// checkedReport is report plus ApplyCheck, as the CLI produces it.
func checkedReport(t *testing.T, path string) *Usage {
	t.Helper()
	program, err := compiler.ReadProgram(path)
	if err != nil {
		t.Fatal(err)
	}
	u := report(t, path)
	cp, err := compiler.Check(program)
	ApplyCheck(u, cp, err)
	return u
}

// The uses summary flags each feature beyond the original subset; full swap
// (the pinned baseline) uses none of them.
func TestUsesSummary(t *testing.T) {
	if got := checkedReport(t, filepath.Join("..", "..", "examples", "full-swap")).Uses; got != (Uses{Checked: true}) {
		t.Errorf("full swap uses: %+v", got)
	}
	for name, tc := range map[string]struct {
		src  string
		want Uses
	}{
		"len results only": {`func Process(s, i []byte) uint64 { if len(s) > 2 { return uint64(len(i)) }; return 0 }`,
			Uses{Checked: true}},
		"signed operation": {`func Process(s, i []byte) uint64 { n := len(s); n++; return uint64(n) }`,
			Uses{Checked: true, SignedIntegers: true}},
		"signed type": {`func Process(s, i []byte) uint64 { var x int32 = 3; return uint64(x) }`,
			Uses{Checked: true, SignedIntegers: true}},
		"heap move": {`type N struct{ v uint64; next *N }
func link(v uint64) *N { n := N{v: v}; return &n }
func Process(s, i []byte) uint64 { return link(7).v }`,
			Uses{Checked: true, Allocation: true, HeapMovedLocals: 1}},
		"allocation and range": {`func Process(s, i []byte) uint64 { a := make([]uint16, 3); var t uint64; for _, v := range a { t = t + uint64(v) }; return t }`,
			Uses{Checked: true, Allocation: true, Uint16: true, Range: true}},
		"math/bits and generics": {`import "math/bits"
func Id[T any](x T) T { return x }
func Process(s, i []byte) uint64 { h, _ := bits.Mul64(Id(uint64(3)), 4); return h }`,
			Uses{Checked: true, MathBits: true, Generics: true}},
		"interface value": {`func Process(s, i []byte) uint64 { var x any = s; _ = x; return 0 }`,
			Uses{Checked: true, Interfaces: true}},
		"error value": {`func Process(s, i []byte) uint64 { var e error; _ = e; return 0 }`,
			Uses{Checked: true, Interfaces: true}},
		"strings": {`func Process(s, i []byte) uint64 { x := string(i); return uint64(len(x + "a")) }`,
			Uses{Checked: true, Strings: true}},
		"map rejected": {`func Process(s, i []byte) uint64 { var m map[uint8]uint8; _ = m; return 0 }`,
			Uses{}},
	} {
		dir := t.TempDir()
		if err := os.WriteFile(filepath.Join(dir, "program.go"), []byte("package main\n"+tc.src+"\n"), 0644); err != nil {
			t.Fatal(err)
		}
		got := checkedReport(t, dir).Uses
		if tc.want.Checked {
			got.CheckError = ""
		}
		if !tc.want.Checked && got.CheckError == "" {
			t.Errorf("%s: expected a Check error", name)
		}
		got.CheckError = ""
		if got != tc.want {
			t.Errorf("%s: %+v, want %+v", name, got, tc.want)
		}
	}
}
